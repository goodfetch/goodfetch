#!/usr/bin/env bash
# Renders Homebrew formulas (`Formula/goodfetch-collie.rb` and
# `Formula/goodfetch-foxhound.rb`) for tap `goodfetch/tap` (repository
# `goodfetch/homebrew-tap`; ADRs 0090 and 0094, issue 144) from a release's
# `SHA256SUMS`.
#
# Usage: ci/release/render-homebrew-formulas.sh <version> <sha256sums> <out-dir>
set -euo pipefail

version=${1:?usage: ci/release/render-homebrew-formulas.sh <version> <sha256sums> <out-dir>}
sums=${2:?usage: ci/release/render-homebrew-formulas.sh <version> <sha256sums> <out-dir>}
out_dir=${3:?usage: ci/release/render-homebrew-formulas.sh <version> <sha256sums> <out-dir>}

version=${version#v}
repo=${GOODFETCH_REPO:-goodfetch/goodfetch}

sha_for() {
  local archive=$1
  local digest
  digest=$(awk -v f="$archive" '$2 == f || $2 == ("*" f) {print $1; exit}' "$sums")
  if [[ -z "$digest" ]]; then
    echo "error: missing checksum for ${archive} in ${sums}" >&2
    exit 1
  fi
  printf '%s' "$digest"
}

render_formula() {
  local class_name=$1
  local bin_name=$2
  local desc=$3
  local base="https://github.com/${repo}/releases/download/v${version}"

  local mac_arm mac_x64 linux_arm linux_x64
  mac_arm=$(sha_for "${bin_name}-aarch64-apple-darwin.tar.xz")
  mac_x64=$(sha_for "${bin_name}-x86_64-apple-darwin.tar.xz")
  linux_arm=$(sha_for "${bin_name}-aarch64-unknown-linux-musl.tar.xz")
  linux_x64=$(sha_for "${bin_name}-x86_64-unknown-linux-musl.tar.xz")

  mkdir -p "${out_dir}/Formula"
  cat >"${out_dir}/Formula/${bin_name}.rb" <<EOF
# Generated by ci/release/render-homebrew-formulas.sh for v${version} (ADRs 0090 and 0094).
class ${class_name} < Formula
  desc "${desc}"
  homepage "https://goodfetch.dev"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/${bin_name}-aarch64-apple-darwin.tar.xz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/${bin_name}-x86_64-apple-darwin.tar.xz"
      sha256 "${mac_x64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/${bin_name}-aarch64-unknown-linux-musl.tar.xz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/${bin_name}-x86_64-unknown-linux-musl.tar.xz"
      sha256 "${linux_x64}"
    end
  end

  def install
    bin.install "${bin_name}"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/${bin_name} --version")
  end
end
EOF
}

render_formula "GoodfetchCollie" "goodfetch-collie" "Goodfetch Collie browser automation CLI and engine"
render_formula "GoodfetchFoxhound" "goodfetch-foxhound" "Goodfetch Foxhound crawling CLI and engine (contains Collie)"
