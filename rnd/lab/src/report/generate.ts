// Decisions report generated from the registry and the computed verdicts only: no figure is typed by hand.
import type { Registry } from '../core/decisions.ts';

type VerdictLike = {
  decisionId: string; outcome: string; n: number; requiredN: number | null; option?: string; baseline?: string; metricId?: string;
  estimate: { ratio: number; ratioCi: number[]; interval: string; wilcoxon: { pValue: number } } | null;
  gates: { id: string; ok: boolean; evaluated?: boolean }[]; host: { required: string; observed: string | null; eligible: boolean }; inputs?: { runs: string[] };
  stratum?: Record<string, unknown>; comparisons?: Omit<VerdictLike, 'decisionId' | 'comparisons'>[];
};

const outcomeLabel: Record<string, string> = {
  better: 'option better', worse: 'option worse', equivalent: 'equivalent', trivial: 'real difference below the margin',
  'non-inferior': 'non-inferior', inconclusive: 'inconclusive', 'blocked-by-contract': 'blocked by a contract', 'insufficient-n': 'insufficient blocks', 'contract-met': 'contract met'
};
const figure = (value: number) => Number(value.toPrecision(3)).toString();

export function renderDecisionsReport(registry: Registry, verdicts: VerdictLike[]): string {
  const byId = new Map(verdicts.map(verdict => [verdict.decisionId, verdict]));
  const lines = ['# Lab decisions', '', 'Report generated by `pnpm lab report` from `decisions/` and `verdicts/`. Every figure comes from the computed verdicts; no value is typed by hand.', '',
    '| Decision | Status | Verdict | Estimate option / baseline | Blocks | Host | Gates |', '| --- | --- | --- | --- | --- | --- | --- |'];
  for (const decision of [...registry.decisions].sort((a, b) => a.id.localeCompare(b.id))) {
    const verdict = byId.get(decision.id);
    if (decision.kind === 'product') { lines.push(`| ${decision.id} | ${decision.status} | product: ${decision.evidence.map(e => e.ref).join(', ') || 'no evidence'} | | | | |`); continue; }
    if (!verdict) { lines.push(`| ${decision.id} | ${decision.status} | not computed yet | | | requires ${decision.hostClass?.decision ?? '?'} | ${(decision.contractGates ?? []).join(', ')} |`); continue; }
    // A decision with several options gets one row per option compared with the baseline.
    for (const [index, row] of (verdict.comparisons?.length ? verdict.comparisons : [verdict]).entries()) {
      const estimate = row.estimate ? `${figure(row.estimate.ratio)} [${row.estimate.ratioCi.map(figure).join(' ; ')}] (${row.estimate.interval})` : '';
      const blocks = row.requiredN === null ? `${row.n}` : `${row.n} of ${row.requiredN} required`;
      const host = `${row.host.observed ?? 'none'} / requires ${row.host.required}${row.host.eligible ? '' : ' (not eligible)'}`;
      const gates = row.gates.map(gate => `${gate.id} ${gate.evaluated === false ? 'not evaluated' : gate.ok ? 'ok' : 'failed'}`).join(', ');
      const strataLabel = row.stratum && (verdict.comparisons?.length ?? 0) > 1 ? ` [${Object.entries(row.stratum).filter(([key]) => key !== 'browserHost').map(([key, value]) => `${key} ${value}`).join(', ')}]` : '';
      const label = verdict.comparisons?.length ? `${row.option} / ${row.baseline}${strataLabel}: ` : '';
      lines.push(`| ${index === 0 ? decision.id : ''} | ${index === 0 ? decision.status : ''} | ${label}${outcomeLabel[row.outcome] ?? row.outcome} | ${estimate} | ${blocks} | ${host} | ${gates} |`);
    }
  }
  lines.push('', 'A verdict serves a decision only if the observed host reaches the required class and every contract gate passes.', '');
  return lines.join('\n');
}
