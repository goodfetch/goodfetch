//! The bindings of Chrome's debugging protocol (CDP) in `goodfetch-cdp` (spec #577's CDP
//! crate): one Rust module per domain of the protocol file the pinned
//! Chromium serves, with a struct per object type, an enum per enumerated
//! string, and per command its params and returns, per event its params,
//! each tied to its method's name. The engine sends and reads them; no
//! generated type reaches the SDK API, whose CDP session carries JSON
//! values (ADRs 0085 and 0099).
//!
//! The text is formatted with the pinned toolchain's `rustfmt`, so
//! `cargo fmt --check` and `xtask codegen --check` agree on it. A workspace
//! without the protocol file gets no bindings.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

use anyhow::{Context as _, Result, bail};
use serde::Deserialize;

/// The CDP crate, whose bindings these are.
const CRATE: &str = "crates/goodfetch-cdp";

/// The protocol file of the pinned Chromium, as its `/json/protocol` serves
/// it.
pub(super) const PROTOCOL: &str = "crates/goodfetch-cdp/protocol.json";

/// The folder of the generated domain modules.
pub(super) const FOLDER: &str = "crates/goodfetch-cdp/src/generated";

/// The module that declares them.
const MODULE: &str = "crates/goodfetch-cdp/src/generated.rs";

#[derive(Deserialize)]
struct Protocol {
    domains: Vec<Domain>,
}

#[derive(Deserialize)]
struct Domain {
    #[serde(rename = "domain")]
    name: String,
    #[serde(default)]
    types: Vec<TypeDefinition>,
    #[serde(default)]
    commands: Vec<Method>,
    #[serde(default)]
    events: Vec<Method>,
}

#[derive(Deserialize)]
struct TypeDefinition {
    id: String,
    #[serde(rename = "type")]
    kind: String,
    #[serde(rename = "enum")]
    variants: Option<Vec<String>>,
    properties: Option<Vec<Property>>,
    items: Option<Items>,
}

#[derive(Deserialize)]
struct Method {
    name: String,
    #[serde(default)]
    parameters: Vec<Property>,
    #[serde(default)]
    returns: Vec<Property>,
}

#[derive(Deserialize)]
struct Property {
    name: String,
    #[serde(rename = "type")]
    kind: Option<String>,
    #[serde(rename = "$ref")]
    reference: Option<String>,
    #[serde(rename = "enum")]
    variants: Option<Vec<String>>,
    items: Option<Items>,
    #[serde(default)]
    optional: bool,
}

#[derive(Deserialize)]
struct Items {
    #[serde(rename = "type")]
    kind: Option<String>,
    #[serde(rename = "$ref")]
    reference: Option<String>,
}

/// Every generated file by its path; none for a workspace without the CDP
/// crate.
///
/// # Errors
///
/// When the CDP crate's protocol file is missing, which would otherwise
/// plan no bindings and so delete every generated one, or does not read.
pub(super) fn generate(root: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    let path = root.join(PROTOCOL);
    if !path.exists() {
        if root.join(CRATE).exists() {
            bail!("{PROTOCOL} is missing, so no CDP binding can be generated: restore the file");
        }
        return Ok(BTreeMap::new());
    }
    let text =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let protocol: Protocol =
        serde_json::from_str(&text).with_context(|| format!("reading {PROTOCOL}"))?;
    let structs = Structs::of(&protocol);
    let mut files = BTreeMap::new();
    let mut declarations = String::from(HEADER);
    declarations.push_str(
        "\n//! The protocol's domains, one module each, generated from `protocol.json`.\n\n",
    );
    for domain in &protocol.domains {
        let module = snake_case(&domain.name);
        let _ = writeln!(declarations, "pub mod {module};");
        let text = Writer::new(domain, &structs).domain()?;
        files.insert(
            format!("{FOLDER}/{module}.rs"),
            rustfmt(&text).with_context(|| format!("formatting the {} domain", domain.name))?,
        );
    }
    files.insert(MODULE.to_owned(), rustfmt(&declarations)?);
    Ok(files)
}

const HEADER: &str = "// Generated by `xtask codegen` from `protocol.json`: never edit by hand.\n";

/// Formats `text` with the toolchain's `rustfmt`.
fn rustfmt(text: &str) -> Result<Vec<u8>> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("starting rustfmt")?;
    child
        .stdin
        .take()
        .context("rustfmt's stdin")?
        .write_all(text.as_bytes())
        .context("writing to rustfmt")?;
    let output = child.wait_with_output().context("waiting for rustfmt")?;
    if !output.status.success() {
        bail!(
            "rustfmt refused the generated text: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    Ok(output.stdout)
}

/// The object types of every domain, by `Domain.Type`, with the object
/// types each reaches through a field that is not a list, so a field that
/// leads back to its own struct is boxed.
struct Structs {
    edges: BTreeMap<String, BTreeSet<String>>,
}

impl Structs {
    fn of(protocol: &Protocol) -> Self {
        let objects: BTreeSet<String> = protocol
            .domains
            .iter()
            .flat_map(|domain| {
                domain
                    .types
                    .iter()
                    .filter(|definition| definition.properties.is_some())
                    .map(|definition| format!("{}.{}", domain.name, definition.id))
            })
            .collect();
        let mut edges = BTreeMap::new();
        for domain in &protocol.domains {
            for definition in &domain.types {
                let Some(properties) = &definition.properties else {
                    continue;
                };
                let reached = properties
                    .iter()
                    .filter_map(|property| property.reference.as_deref())
                    .map(|reference| qualified(&domain.name, reference))
                    .filter(|target| objects.contains(target))
                    .collect();
                edges.insert(format!("{}.{}", domain.name, definition.id), reached);
            }
        }
        Self { edges }
    }

    /// Whether `from` reaches `to` through fields that are not lists.
    fn reaches(&self, from: &str, to: &str) -> bool {
        let mut seen = BTreeSet::new();
        let mut pending = vec![from.to_owned()];
        while let Some(current) = pending.pop() {
            if current == to {
                return true;
            }
            if !seen.insert(current.clone()) {
                continue;
            }
            if let Some(next) = self.edges.get(&current) {
                pending.extend(next.iter().cloned());
            }
        }
        false
    }
}

/// `Type` within `domain` as `Domain.Type`.
fn qualified(domain: &str, reference: &str) -> String {
    if reference.contains('.') {
        reference.to_owned()
    } else {
        format!("{domain}.{reference}")
    }
}

/// Writes one domain's module.
struct Writer<'a> {
    domain: &'a Domain,
    structs: &'a Structs,
    text: String,
    names: BTreeSet<String>,
}

impl<'a> Writer<'a> {
    fn new(domain: &'a Domain, structs: &'a Structs) -> Self {
        Self {
            domain,
            structs,
            text: String::new(),
            names: BTreeSet::new(),
        }
    }

    fn domain(mut self) -> Result<String> {
        let _ = write!(
            self.text,
            "{HEADER}\n//! The `{}` domain.\n\nuse serde::{{Deserialize, Serialize}};\n\n",
            self.domain.name
        );
        for definition in &self.domain.types {
            self.type_definition(definition)?;
        }
        for command in &self.domain.commands {
            self.command(command)?;
        }
        for event in &self.domain.events {
            self.event(event)?;
        }
        Ok(self.text)
    }

    /// Claims the item name `name` in the module.
    fn claim(&mut self, name: &str) -> Result<()> {
        if !self.names.insert(name.to_owned()) {
            bail!(
                "two items of the {} domain are named `{name}`",
                self.domain.name
            );
        }
        Ok(())
    }

    fn type_definition(&mut self, definition: &TypeDefinition) -> Result<()> {
        let name = definition.id.clone();
        if let Some(variants) = &definition.variants {
            return self.enumeration(&name, variants);
        }
        if let Some(properties) = &definition.properties {
            let owner = format!("{}.{}", self.domain.name, definition.id);
            return self.structure(&name, &definition.id, properties, Some(&owner));
        }
        self.claim(&name)?;
        let aliased = match definition.kind.as_str() {
            "array" => {
                let items = definition
                    .items
                    .as_ref()
                    .with_context(|| format!("the list type {name} names no items"))?;
                format!("Vec<{}>", self.items(items)?)
            }
            "object" => "serde_json::Map<String, serde_json::Value>".to_owned(),
            other => primitive(other)?.to_owned(),
        };
        let _ = writeln!(self.text, "pub type {name} = {aliased};\n");
        Ok(())
    }

    fn enumeration(&mut self, name: &str, variants: &[String]) -> Result<()> {
        self.claim(name)?;
        let _ = writeln!(
            self.text,
            "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]\npub enum {name} {{"
        );
        let mut used = BTreeSet::new();
        for value in variants {
            let mut variant = upper_camel(value);
            if variant.is_empty() || variant.starts_with(|first: char| first.is_ascii_digit()) {
                variant.insert(0, 'V');
            }
            if variant == "Self" {
                variant.push_str("Value");
            }
            let base = variant.clone();
            let mut count = 2;
            while used.contains(&variant) || variant == "Unlisted" {
                variant = format!("{base}{count}");
                count += 1;
            }
            used.insert(variant.clone());
            let _ = writeln!(
                self.text,
                "    #[serde(rename = {value:?})]\n    {variant},"
            );
        }
        let _ = writeln!(
            self.text,
            "    /// A value this revision's protocol does not list.\n    #[serde(other)]\n    Unlisted,\n}}\n"
        );
        Ok(())
    }

    /// A struct `name` of `properties`; `owner` is its `Domain.Type`, for a
    /// type of the protocol, whose fields leading back to it are boxed.
    fn structure(
        &mut self,
        name: &str,
        inline_prefix: &str,
        properties: &[Property],
        owner: Option<&str>,
    ) -> Result<()> {
        self.claim(name)?;
        let mut fields = String::new();
        let mut inline = Vec::new();
        for property in properties {
            let mut field_type = match (&property.variants, &property.kind) {
                (Some(variants), _) => {
                    let inline_name =
                        format!("{inline_prefix}{}", upper_camel_word(&property.name));
                    inline.push((inline_name.clone(), variants.clone()));
                    inline_name
                }
                _ => self.property(property)?,
            };
            if let (Some(owner), Some(reference)) = (owner, &property.reference) {
                let target = qualified(&self.domain.name, reference);
                if self.structs.reaches(&target, owner) {
                    field_type = format!("Box<{field_type}>");
                }
            }
            let field = field_name(&property.name);
            let rename = if unescaped(&field) == property.name {
                String::new()
            } else {
                format!("rename = {:?}", property.name)
            };
            if property.optional {
                let attributes = if rename.is_empty() {
                    "default, skip_serializing_if = \"Option::is_none\"".to_owned()
                } else {
                    format!("{rename}, default, skip_serializing_if = \"Option::is_none\"")
                };
                let _ = writeln!(
                    fields,
                    "    #[serde({attributes})]\n    pub {field}: Option<{field_type}>,"
                );
            } else {
                if !rename.is_empty() {
                    let _ = writeln!(fields, "    #[serde({rename})]");
                }
                let _ = writeln!(fields, "    pub {field}: {field_type},");
            }
        }
        // A struct whose every field may be absent has a default: all absent.
        let default = if properties.iter().all(|property| property.optional) {
            "Default, "
        } else {
            ""
        };
        let _ = writeln!(
            self.text,
            "#[derive(Clone, Debug, {default}PartialEq, Serialize, Deserialize)]\npub struct {name} {{\n{fields}}}\n"
        );
        for (inline_name, variants) in inline {
            self.enumeration(&inline_name, &variants)?;
        }
        Ok(())
    }

    fn command(&mut self, command: &Method) -> Result<()> {
        let base = upper_camel_word(&command.name);
        let params = format!("{base}Params");
        let returns = format!("{base}Returns");
        self.structure(&params, &base, &command.parameters, None)?;
        self.structure(&returns, &format!("{base}Returned"), &command.returns, None)?;
        let _ = writeln!(
            self.text,
            "impl crate::Command for {params} {{\n    const METHOD: &'static str = \"{}.{}\";\n    type Returns = {returns};\n}}\n",
            self.domain.name, command.name
        );
        Ok(())
    }

    fn event(&mut self, event: &Method) -> Result<()> {
        let base = upper_camel_word(&event.name);
        let name = format!("{base}Event");
        self.structure(&name, &base, &event.parameters, None)?;
        let _ = writeln!(
            self.text,
            "impl crate::Event for {name} {{\n    const METHOD: &'static str = \"{}.{}\";\n}}\n",
            self.domain.name, event.name
        );
        Ok(())
    }

    fn property(&self, property: &Property) -> Result<String> {
        if let Some(reference) = &property.reference {
            return Ok(self.reference(reference));
        }
        let kind = property
            .kind
            .as_deref()
            .with_context(|| format!("the field {} has no type", property.name))?;
        if kind == "array" {
            let items = property
                .items
                .as_ref()
                .with_context(|| format!("the list field {} names no items", property.name))?;
            return Ok(format!("Vec<{}>", self.items(items)?));
        }
        if kind == "object" {
            return Ok("serde_json::Map<String, serde_json::Value>".to_owned());
        }
        Ok(primitive(kind)?.to_owned())
    }

    fn items(&self, items: &Items) -> Result<String> {
        if let Some(reference) = &items.reference {
            return Ok(self.reference(reference));
        }
        match items.kind.as_deref() {
            Some("object") => Ok("serde_json::Map<String, serde_json::Value>".to_owned()),
            Some(kind) => Ok(primitive(kind)?.to_owned()),
            None => bail!("a list's items have neither a type nor a reference"),
        }
    }

    fn reference(&self, reference: &str) -> String {
        match reference.split_once('.') {
            Some((domain, name)) if domain != self.domain.name => {
                format!("super::{}::{name}", snake_case(domain))
            }
            Some((_, name)) => name.to_owned(),
            None => reference.to_owned(),
        }
    }
}

fn primitive(kind: &str) -> Result<&'static str> {
    Ok(match kind {
        "string" | "binary" => "String",
        "integer" => "i64",
        "number" => "f64",
        "boolean" => "bool",
        "any" => "serde_json::Value",
        other => bail!("the protocol's type `{other}` has no Rust type"),
    })
}

/// The Rust keywords a protocol field is named after.
const KEYWORDS: [&str; 2] = ["type", "override"];

fn field_name(name: &str) -> String {
    let snake = snake_case(name);
    if KEYWORDS.contains(&snake.as_str()) {
        format!("r#{snake}")
    } else {
        snake
    }
}

fn unescaped(field: &str) -> &str {
    field.strip_prefix("r#").unwrap_or(field)
}

/// `frameId` as `frame_id`, `DOMDebugger` as `dom_debugger`.
pub(super) fn snake_case(name: &str) -> String {
    let characters: Vec<char> = name.chars().collect();
    let mut snake = String::new();
    for (index, character) in characters.iter().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            let previous = characters[index - 1];
            let next_is_lower = characters
                .get(index + 1)
                .is_some_and(char::is_ascii_lowercase);
            if previous.is_ascii_lowercase()
                || previous.is_ascii_digit()
                || (previous.is_ascii_uppercase() && next_is_lower)
            {
                snake.push('_');
            }
        }
        if character.is_ascii_alphanumeric() {
            snake.push(character.to_ascii_lowercase());
        } else if !snake.ends_with('_') {
            snake.push('_');
        }
    }
    snake
}

/// A command's or a field's name with its first letter in capitals:
/// `getResponseBody` as `GetResponseBody`.
fn upper_camel_word(name: &str) -> String {
    let mut characters = name.chars();
    characters.next().map_or_else(String::new, |first| {
        first.to_ascii_uppercase().to_string() + characters.as_str()
    })
}

/// An enumerated value as a variant's name: each word capitalized and the
/// rest lowercase, `back-forward` as `BackForward` and `XHR` as `Xhr`.
fn upper_camel(value: &str) -> String {
    snake_case(value)
        .split('_')
        .filter(|word| !word.is_empty())
        .map(upper_camel_word)
        .collect()
}

#[cfg(test)]
mod tests {
    use goodfetch_test_support::TestEnv;

    use super::{CRATE, PROTOCOL, generate, snake_case, upper_camel};

    /// A workspace whose CDP crate lacks its protocol file fails the
    /// generation, naming the file, rather than planning no bindings, which
    /// would delete every generated one.
    #[test]
    fn a_missing_protocol_file_fails_the_generation() {
        let env = TestEnv::new();
        std::fs::create_dir_all(env.folder().join(CRATE)).unwrap();

        let generated = generate(env.folder());

        assert!(
            generated
                .as_ref()
                .is_err_and(|error| error.to_string().contains(PROTOCOL)),
            "{:?}",
            generated.map(|files| files.len())
        );
    }

    #[test]
    fn names_become_rust_names() {
        assert_eq!(
            [
                "frameId",
                "DOMDebugger",
                "IndexedDB",
                "PWA",
                "requestURL",
                "WebMCP"
            ]
            .map(snake_case),
            [
                "frame_id",
                "dom_debugger",
                "indexed_db",
                "pwa",
                "request_url",
                "web_mcp"
            ]
        );
        assert_eq!(
            ["back-forward", "XHR", "Document", "net::ERR_FAILED"].map(upper_camel),
            ["BackForward", "Xhr", "Document", "NetErrFailed"]
        );
    }
}
