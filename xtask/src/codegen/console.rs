//! The Console's operation map (spec #592; ADRs 0068 and 0099): every
//! operation of Collie's catalog projection, those kept off agent surfaces
//! included (a person's answers, the SDKs' own), each with its params and
//! result in wire names, which types the Console's raw catalog call so a
//! screen's call to an operation outside the catalog fails the type check;
//! each event's class, lossless or telemetry, which the Console's
//! subscription marks its events with; and each operation's class, read,
//! idempotent write or Effect, which tells the Console's Client what it
//! may send again after a reconnect. The types come from Collie's client
//! package, whose generated layer defines every type of the projection.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context as _, Result};
use serde_json::Value;

use crate::features::FoxhoundNames;

/// Where Collie's Console keeps its generated files.
pub(super) const FOLDER: &str = "console/collie/src/generated";

/// Collie's Console package, whose map is written only where it exists,
/// so a workspace without the Console gets none.
const PACKAGE: &str = "console/collie/package.json";

/// Where the types come from.
const CLIENT_PACKAGE: &str = "@goodfetch/collie-client/generated";

const HEADER: &str = "// Generated by `xtask codegen` from the catalog; never edit by hand.\n";

/// The files of `FOLDER`, by name, from Collie's projection; none when the
/// workspace at `root` has no Console.
pub(super) fn files(
    root: &Path,
    collie: &Value,
    foxhound_names: &FoxhoundNames,
) -> Result<Vec<(&'static str, String)>> {
    if !root.join(PACKAGE).is_file() {
        return Ok(Vec::new());
    }
    Ok(vec![
        ("operations.ts", operations(collie)?),
        ("foxhound.ts", foxhound(foxhound_names)),
    ])
}

/// The operations only Foxhound carries, from the catalog's Product marks:
/// what Collie's engine refuses with `not_in_product`, and what Collie's
/// Console names a Foxhound view of a run by, never importing Foxhound's
/// screens (ADRs 0087, 0095 and 0098).
fn foxhound(foxhound_names: &FoxhoundNames) -> String {
    let list = foxhound_names
        .get("operations")
        .into_iter()
        .flatten()
        .map(|name| format!("{name:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "{HEADER}\n/** The operations only Foxhound carries (ADRs 0087 and 0095): Collie's engine refuses each with `not_in_product`. */\nexport const FOXHOUND_OPERATIONS = [{list}] as const;\n\n/** An operation only Foxhound carries. */\nexport type FoxhoundOperation = (typeof FOXHOUND_OPERATIONS)[number];\n"
    )
}

/// The name of the bundle type `reference`, `{"$ref": "#/$defs/<name>"}`.
fn type_name(reference: &Value) -> Result<&str> {
    reference
        .get("$ref")
        .and_then(Value::as_str)
        .and_then(|reference| reference.strip_prefix("#/$defs/"))
        .with_context(|| format!("`{reference}` is no reference to a type of the bundle"))
}

fn entries<'a>(collie: &'a Value, section: &str) -> Result<&'a Vec<Value>> {
    collie
        .get(section)
        .and_then(Value::as_array)
        .with_context(|| format!("Collie's projection has no `{section}`"))
}

fn name(entry: &Value) -> Result<&str> {
    entry
        .get("name")
        .and_then(Value::as_str)
        .with_context(|| format!("an entry of Collie's projection has no name: {entry}"))
}

fn operations(collie: &Value) -> Result<String> {
    let mut rows = Vec::new();
    let mut types = BTreeSet::new();
    for operation in entries(collie, "operations")? {
        let params = type_name(&operation["params"])?;
        let result = type_name(&operation["result"])?;
        types.extend([params, result]);
        let class = operation
            .get("class")
            .and_then(Value::as_str)
            .with_context(|| {
                format!(
                    "the operation `{}` has no class",
                    name(operation).unwrap_or("?")
                )
            })?;
        rows.push((name(operation)?, params, result, class));
    }
    let mut classes = Vec::new();
    for event in entries(collie, "events")? {
        let class = event
            .get("class")
            .and_then(Value::as_str)
            .with_context(|| format!("the event `{}` has no class", name(event).unwrap_or("?")))?;
        classes.push((name(event)?, class));
    }
    types.insert("CollieEventPayloads");
    let names: Vec<&str> = types.into_iter().collect();
    let mut text = format!("{HEADER}\n");
    let _ = writeln!(
        text,
        "import type {{ {} }} from \"{CLIENT_PACKAGE}\";",
        names.join(", ")
    );
    text.push_str("\n/**\n * The params and result of each operation of Collie's catalog, in wire names,\n * those kept off agent surfaces included: what the Console's raw catalog\n * call takes and answers (ADR 0099).\n */\nexport interface ConsoleOperations {\n");
    for (operation, params, result, _) in &rows {
        let _ = writeln!(
            text,
            "  {operation:?}: {{ params: {params}; result: {result} }};"
        );
    }
    text.push_str("}\n\n/** How each of Collie's events travels: `lossless`, never missed, or `telemetry`, coalesced. */\nexport type EventClass = \"lossless\" | \"telemetry\";\n\n/** The class of each of Collie's events. */\nexport const eventClasses: Readonly<Record<keyof CollieEventPayloads, EventClass>> = {\n");
    for (event, class) in &classes {
        let _ = writeln!(text, "  {event:?}: {class:?},");
    }
    text.push_str("};\n\n/** What calling an operation does: `read` changes nothing, `idempotent_write` changes nothing more when called again, and `effect` acts on the world (ADR 0010). */\nexport type OperationClass = \"read\" | \"idempotent_write\" | \"effect\";\n\n/** The class of each operation of Collie's catalog, which tells the Console's Client what it may send again after a reconnect (ADR 0079). */\nexport const operationClasses: Readonly<Record<keyof ConsoleOperations, OperationClass>> = {\n");
    for (operation, _, _, class) in &rows {
        let _ = writeln!(text, "  {operation:?}: {class:?},");
    }
    text.push_str("};\n");
    Ok(text)
}

#[cfg(test)]
mod tests {
    use std::collections::{BTreeMap, BTreeSet};

    use serde_json::json;

    use super::{foxhound, operations};

    /// Covers: story:12-121
    #[test]
    fn the_consoles_foxhound_names_are_the_operations_only_foxhound_carries() {
        let names = BTreeMap::from([
            (
                "operations".to_owned(),
                BTreeSet::from(["run.records".to_owned(), "crawl.start".to_owned()]),
            ),
            (
                "settings".to_owned(),
                BTreeSet::from(["crawl.max_depth".to_owned()]),
            ),
        ]);

        let text = foxhound(&names);

        assert!(
            text.contains(
                "export const FOXHOUND_OPERATIONS = [\"crawl.start\", \"run.records\"] as const;\n"
            ),
            "{text}"
        );
        assert!(
            text.contains(
                "export type FoxhoundOperation = (typeof FOXHOUND_OPERATIONS)[number];\n"
            ),
            "{text}"
        );
        assert!(!text.contains("crawl.max_depth"), "{text}");
    }

    /// Covers: story:12-1, story:12-123
    #[test]
    fn the_consoles_map_holds_every_operation_a_persons_answer_included_and_each_events_class() {
        let collie = json!({
            "operations": [
                { "name": "widget.spin", "class": "effect", "params": { "$ref": "#/$defs/SpinParams" }, "result": { "$ref": "#/$defs/Spun" }, "reach": "all_surfaces" },
                { "name": "widget.raise", "class": "idempotent_write", "params": { "$ref": "#/$defs/RaiseParams" }, "result": { "$ref": "#/$defs/Raised" }, "reach": "person_only" },
            ],
            "events": [
                { "name": "widget.spun", "class": "telemetry", "payload": { "$ref": "#/$defs/Spun" } },
            ],
        });

        let text = operations(&collie).unwrap();

        assert!(
            text.contains("import type { CollieEventPayloads, RaiseParams, Raised, SpinParams, Spun } from \"@goodfetch/collie-client/generated\";"),
            "{text}"
        );
        assert!(
            text.contains("  \"widget.spin\": { params: SpinParams; result: Spun };\n  \"widget.raise\": { params: RaiseParams; result: Raised };\n"),
            "{text}"
        );
        assert!(
            text.contains("  \"widget.spun\": \"telemetry\",\n"),
            "{text}"
        );
        assert!(
            text.contains("export const operationClasses: Readonly<Record<keyof ConsoleOperations, OperationClass>> = {\n  \"widget.spin\": \"effect\",\n  \"widget.raise\": \"idempotent_write\",\n};\n"),
            "{text}"
        );
    }
}
