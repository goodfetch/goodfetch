//! The label values of `goodfetch.counted_work` (ADRs 0050 and 0140): every
//! Shared path and every work of `goodfetch-counted-work`'s rows, written as
//! Rust constants into `goodfetch-protocol`, which declares the metric but
//! may not depend on that crate. `xtask` builds no Goodfetch crate but
//! `goodfetch-protocol` (ADR 0072), so it reads the rows from their one
//! table, the `rows!` invocation in the crate's `lib.rs`, a line a row:
//! `Variant => "name", "path", "work";`. A row added without regenerating is
//! drift.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context as _, Result, bail};

/// The constants' file, relative to the root.
const TABLE: &str = "crates/goodfetch-protocol/generated/counted_work.rs";

/// The rows' table, relative to the root.
const ROWS: &str = "crates/goodfetch-counted-work/src/lib.rs";

/// Where the table opens and closes in [`ROWS`].
const OPENS: &str = "\nrows! {\n";
const CLOSES: &str = "\n}\n";

/// The file, from the committed rows; none in a tree that holds no Counted
/// work, such as a test fixture's.
pub(super) fn generate(root: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    let path = root.join(ROWS);
    if !path.exists() {
        return Ok(BTreeMap::new());
    }
    let source =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let (paths, works) = labels(&source).with_context(|| format!("reading the rows of {ROWS}"))?;
    Ok(BTreeMap::from([(
        TABLE.to_owned(),
        render(&paths, &works).into_bytes(),
    )]))
}

/// Every Shared path and every work the table's rows name, each once.
fn labels(source: &str) -> Result<(BTreeSet<String>, BTreeSet<String>)> {
    let Some((_, rest)) = source.split_once(OPENS) else {
        bail!("no `rows!` table");
    };
    let Some((table, _)) = rest.split_once(CLOSES) else {
        bail!("the `rows!` table does not close");
    };
    let (mut paths, mut works) = (BTreeSet::new(), BTreeSet::new());
    for line in table.lines().map(str::trim) {
        if line.is_empty() || line.starts_with("///") {
            continue;
        }
        let Some((_, quoted)) = line.split_once(" => ") else {
            bail!("a row that is no `Variant => \"name\", \"path\", \"work\";`: {line}");
        };
        let cells: Vec<&str> = quoted
            .trim_end_matches(';')
            .split(", ")
            .map(|cell| cell.trim_matches('"'))
            .collect();
        let [_, shared_path, work] = cells.as_slice() else {
            bail!("a row that is no `Variant => \"name\", \"path\", \"work\";`: {line}");
        };
        paths.insert((*shared_path).to_owned());
        works.insert((*work).to_owned());
    }
    if paths.is_empty() {
        bail!("the `rows!` table has no row");
    }
    Ok((paths, works))
}

/// The file's text: each label's values once, sorted.
fn render(paths: &BTreeSet<String>, works: &BTreeSet<String>) -> String {
    let mut text = String::from(
        "// Generated by `xtask codegen` from `goodfetch-counted-work`'s rows; never\n// edit by hand.\n",
    );
    constant(
        &mut text,
        "Every Shared path a row of Counted work counts on, by name (ADR 0140).",
        "SHARED_PATHS",
        paths,
    );
    constant(
        &mut text,
        "Every work a row of Counted work counts (ADR 0140).",
        "WORKS",
        works,
    );
    text
}

fn constant(text: &mut String, doc: &str, name: &str, values: &BTreeSet<String>) {
    let _ = write!(
        text,
        "\n/// {doc}\nconst {name}: [&str; {}] = [\n",
        values.len()
    );
    for value in values {
        let _ = writeln!(text, "    {value:?},");
    }
    text.push_str("];\n");
}
