//! Deployment templates embedded by both Products' executables (spec #583,
//! issue 1262; ADRs 0049, 0057, 0087, 0090).
//!
//! Reads the single source of truth under `packaging/deploy/` (plus
//! `packaging/oci/seccomp-profile.json`), compresses each file with zstd, and
//! emits:
//! - `crates/goodfetch-collie/generated/deploy/<target>/<file>.zst` and
//!   `crates/goodfetch-collie/generated/deploy.rs`
//! - `crates/foxhound/goodfetch-foxhound/generated/deploy/<target>/<file>.zst`
//!   and `crates/foxhound/goodfetch-foxhound/generated/deploy.rs`
//!
//! A fixture workspace without `packaging/deploy/image-digests.toml` produces
//! no files, matching how `skills` handles workspaces without `skills/`.
#![expect(
    clippy::disallowed_methods,
    reason = "xtask is synchronous; the blocking-fs ban targets async crates (STYLE.md)"
)]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context as _, Result};

use crate::deploy_templates::{COMPOSE_SOURCES, DIGESTS_FILE, ProductDigests, load_digests};
use crate::products;

/// Where Collie's executable embeds its compressed deployment templates.
pub(super) const COLLIE_FOLDER: &str = concat!(products::collie_folder!(), "/generated/deploy");
/// Where Foxhound's executable embeds its compressed deployment templates.
pub(super) const FOXHOUND_FOLDER: &str = concat!(products::foxhound_folder!(), "/generated/deploy");

const COLLIE_LIST: &str = concat!(products::collie_folder!(), "/generated/deploy.rs");
const FOXHOUND_LIST: &str = concat!(products::foxhound_folder!(), "/generated/deploy.rs");

/// Zstd compression level used for embedded deployment templates: deterministic
/// and small (ADR 0057).
const ZSTD_LEVEL: i32 = 19;

pub(super) fn files(root: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    if !root.join(DIGESTS_FILE).is_file() {
        return Ok(BTreeMap::new());
    }
    let digests = load_digests(root)?;

    let mut compressed = Vec::with_capacity(COMPOSE_SOURCES.len());
    for (output_path, source_rel) in COMPOSE_SOURCES {
        let source_path = root.join(source_rel);
        let raw = std::fs::read(&source_path)
            .with_context(|| format!("reading {}", source_path.display()))?;
        let zst = zstd::stream::encode_all(raw.as_slice(), ZSTD_LEVEL)
            .with_context(|| format!("compressing {source_rel} with zstd"))?;
        compressed.push(("compose", output_path, zst));
    }

    let mut out = BTreeMap::new();
    emit_product(
        &mut out,
        "Product::Collie",
        &digests.collie,
        COLLIE_FOLDER,
        COLLIE_LIST,
        &compressed,
    );
    emit_product(
        &mut out,
        "Product::Foxhound",
        &digests.foxhound,
        FOXHOUND_FOLDER,
        FOXHOUND_LIST,
        &compressed,
    );
    Ok(out)
}

fn emit_product(
    out: &mut BTreeMap<String, Vec<u8>>,
    product_expr: &str,
    digests: &ProductDigests,
    folder: &str,
    list_path: &str,
    compressed: &[(&str, &str, Vec<u8>)],
) {
    let mut rs = String::from(
        "// Generated by `xtask codegen` from `packaging/deploy/` and `packaging/oci/seccomp-profile.json`:\n\
         // zstd-compressed deployment templates embedded by the executable; never edit by hand.\n\
         DeployTemplates::new(\n",
    );
    let _ = writeln!(rs, "    {product_expr},");
    let _ = writeln!(rs, "    {:?},", digests.repository);
    let _ = writeln!(rs, "    {:?},", digests.default);
    let _ = writeln!(rs, "    {:?},", digests.nightly);
    rs.push_str("    &[\n");
    for (target, output_path, zst_bytes) in compressed {
        let rel_zst = format!("deploy/{target}/{output_path}.zst");
        out.insert(
            format!("{folder}/{target}/{output_path}.zst"),
            zst_bytes.clone(),
        );
        rs.push_str("        DeployFile {\n");
        rs.push_str("            target: DeployTarget::Compose,\n");
        let _ = writeln!(rs, "            path: {output_path:?},");
        let _ = writeln!(
            rs,
            "            zstd_contents: include_bytes!({rel_zst:?}),"
        );
        rs.push_str("        },\n");
    }
    rs.push_str("    ],\n)\n");
    out.insert(list_path.to_owned(), rs.into_bytes());
}
