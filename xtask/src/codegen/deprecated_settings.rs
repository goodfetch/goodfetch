//! The release notes' list of the deprecated settings keys (ADRs 0030 and
//! 0099): a settings key, which Python's `TypedDict` cannot mark with PEP
//! 702, carries its deprecation in a docstring and a run-time warning
//! only, so the hand-written release notes of each minor take this list,
//! each key with its replacement, from the catalog.

use std::fmt::Write as _;

use anyhow::{Context as _, Result};
use goodfetch_protocol::catalog::Deprecation;
use serde::Deserialize;
use serde_json::Value;

use super::PROTOCOL_GENERATED;

/// Where the list goes.
pub(super) fn path() -> String {
    format!("{PROTOCOL_GENERATED}/deprecated_settings.md")
}

/// A setting of the catalog, as far as the list reads it.
#[derive(Deserialize)]
struct Setting {
    name: String,
    products: Vec<String>,
    #[serde(default)]
    deprecated: Option<Deprecation<String>>,
}

/// The list's Markdown: a row for each deprecated key, in key order.
pub(super) fn generate(catalog: &Value) -> Result<String> {
    let settings: Vec<Setting> = serde_json::from_value(
        catalog
            .get("settings")
            .cloned()
            .context("the catalog has no `settings`")?,
    )
    .context("reading the catalog's settings")?;
    let mut deprecated: Vec<(&Setting, &Deprecation<String>)> = settings
        .iter()
        .filter_map(|setting| setting.deprecated.as_ref().map(|it| (setting, it)))
        .collect();
    deprecated.sort_by(|(left, _), (right, _)| left.name.cmp(&right.name));
    let mut text = "# Deprecated settings keys\n\nGenerated by `xtask codegen` from the catalog; never edit by hand.\n\nThe release notes' deprecations take each key below, with its replacement (ADRs 0030 and 0099). A program that sets one is warned once per process through its SDK's host channel.\n".to_owned();
    if deprecated.is_empty() {
        text.push_str("\nNo settings key is deprecated.\n");
        return Ok(text);
    }
    text.push_str("\n| Key | Products | Since | Removed no earlier than | Replacement | Note |\n| --- | --- | --- | --- | --- | --- |\n");
    for (setting, deprecation) in deprecated {
        let replacement = deprecation
            .replacement
            .as_ref()
            .map_or_else(|| "none".to_owned(), |key| format!("`{key}`"));
        let _ = writeln!(
            text,
            "| `{}` | {} | {} | {} | {replacement} | {} |",
            setting.name,
            setting.products.join(", "),
            deprecation.since,
            deprecation.earliest_removal,
            cell(&deprecation.note)
        );
    }
    Ok(text)
}

/// `text` as one cell of a Markdown table: on one line, its pipes escaped.
fn cell(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

