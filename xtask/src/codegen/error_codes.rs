//! Rust's Error codes as values of `goodfetch-protocol`'s open `ErrorCode`
//! (ADR 0099): an associated constant for each of Collie's codes and a free
//! constant of Foxhound's `error_code` module for each of Foxhound's, from
//! the catalog's Product marks, so a code the catalog adds reaches Rust with
//! no hand work.

use std::fmt::Write as _;

use anyhow::{Result, bail};
use goodfetch_protocol::error_code::ErrorCode;
use serde_json::Value;

use super::PROTOCOL_GENERATED;

/// The associated items `ErrorCode` declares by hand, which no code's
/// constant may shadow.
const RESERVED: [&str; 2] = ["MAX_LEN", "COLLIE"];

/// One code of the catalog, as its constant says it.
struct Code<'a> {
    name: &'a str,
    group: &'a str,
    retryable: bool,
    description: &'a str,
}

impl Code<'_> {
    fn constant(&self, indent: &str, visibility: &str, of: &str) -> String {
        let retry = if self.retryable {
            "retryable"
        } else {
            "not retryable"
        };
        let mut text = format!(
            "{indent}/// `{}`, in the `{}` group, {retry}.\n{indent}///\n",
            self.name, self.group
        );
        for line in self.description.lines() {
            let _ = writeln!(text, "{indent}/// {line}");
        }
        let _ = writeln!(
            text,
            "{indent}{visibility}const {}: {of} = ErrorCode::from_static({:?});",
            self.name.to_uppercase(),
            self.name
        );
        text
    }
}

/// The two files by path: Collie's associated constants and Foxhound's
/// free ones.
pub(super) fn files(catalog: &Value) -> Result<[(String, Vec<u8>); 2]> {
    let (collie, foxhound) = generate(catalog)?;
    Ok([
        (
            format!("{PROTOCOL_GENERATED}/error_codes.rs"),
            collie.into_bytes(),
        ),
        (
            format!("{PROTOCOL_GENERATED}/foxhound_error_codes.rs"),
            foxhound.into_bytes(),
        ),
    ])
}

/// The two files' text, as `(Collie, Foxhound)`.
fn generate(catalog: &Value) -> Result<(String, String)> {
    let mut collie = Vec::new();
    let mut foxhound = Vec::new();
    for entry in catalog
        .get("error_codes")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        let text = |key: &str| entry.get(key).and_then(Value::as_str).unwrap_or_default();
        let code = Code {
            name: text("name"),
            group: text("group"),
            retryable: entry.get("retryable").and_then(Value::as_bool) == Some(true),
            description: text("description"),
        };
        if code.name.len() > ErrorCode::MAX_LEN {
            bail!(
                "the Error code `{}` is {} bytes, longer than the {} Rust's ErrorCode holds inline (ADR 0099)",
                code.name,
                code.name.len(),
                ErrorCode::MAX_LEN
            );
        }
        if RESERVED.contains(&code.name.to_uppercase().as_str()) {
            bail!(
                "the Error code `{}` would shadow `ErrorCode::{}`",
                code.name,
                code.name.to_uppercase()
            );
        }
        match text("product") {
            "foxhound" => foxhound.push(code),
            _ => collie.push(code),
        }
    }

    let mut collie_text = String::from(
        "// Generated by `xtask codegen` from the catalog's Error codes; never edit by hand.\n\nimpl ErrorCode {\n",
    );
    for code in &collie {
        collie_text.push_str(&code.constant("    ", "pub ", "Self"));
        collie_text.push('\n');
    }
    let _ = write!(
        collie_text,
        "    /// Every Error code of Collie's catalog, in the catalog's order.\n    pub const COLLIE: &[Self] = &[{}];\n}}\n",
        collie
            .iter()
            .map(|code| format!("Self::{}", code.name.to_uppercase()))
            .collect::<Vec<_>>()
            .join(", ")
    );

    let mut foxhound_text = String::from(
        "// Generated by `xtask codegen` from the catalog's Error codes; never edit by hand.\n",
    );
    for code in &foxhound {
        foxhound_text.push('\n');
        foxhound_text.push_str(&code.constant("", "pub ", "ErrorCode"));
    }
    let _ = write!(
        foxhound_text,
        "\n/// Every Error code only Foxhound's catalog carries, in the catalog's order.\npub const ALL: &[ErrorCode] = &[{}];\n",
        foxhound
            .iter()
            .map(|code| code.name.to_uppercase())
            .collect::<Vec<_>>()
            .join(", ")
    );
    Ok((collie_text, foxhound_text))
}
