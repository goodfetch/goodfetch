//! The names of every entry only Foxhound carries, from the catalog's
//! Product marks, as Rust constants in `goodfetch-protocol`, a crate both
//! Products link (ADRs 0087 and 0095). Every section of the catalog gets its
//! list, so a contract that joins the catalog joins this file.

use std::fmt::Write as _;

use serde_json::Value;

use crate::features::FoxhoundNames;

/// The table: each section's names only Foxhound carries, every section
/// listed, empty or not. The Feature inventory reads it for each Feature's
/// Products (ADR 0094).
pub(super) fn table(catalog: &Value) -> FoxhoundNames {
    let sections = catalog.as_object().into_iter().flatten();
    sections
        .filter_map(|(section, entries)| Some((section, entries.as_array()?)))
        .map(|(section, entries)| {
            let names = entries
                .iter()
                .filter(|entry| entry.get("product").and_then(Value::as_str) == Some("foxhound"))
                .filter_map(|entry| entry.get("name").and_then(Value::as_str))
                .map(str::to_owned)
                .collect();
            (section.clone(), names)
        })
        .collect()
}

pub(super) fn render(table: &FoxhoundNames) -> String {
    let mut text = String::from(
        "// Generated by `xtask codegen` from the catalog's Product marks; never edit by hand.\n",
    );
    for (section, names) in table {
        let list = names
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = write!(
            text,
            "\n/// The {} only Foxhound carries.\npub const {}: &[&str] = &[{list}];\n",
            section.replace('_', " "),
            section.to_uppercase(),
        );
    }
    text
}
