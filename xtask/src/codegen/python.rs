//! The Python layer of one SDK package (ADRs 0038 and 0095): pydantic v2
//! models from `datamodel-code-generator`, and, written here, each operation
//! as an async method and a sync one, the event registry, one exception class
//! per Error code (the base and the seven group classes in Collie's client
//! package), the base class of the handlers of each Plugin kind, with the
//! catalog's descriptions as Google-style docstrings and its Experimental and
//! deprecated markers. Foxhound's layer imports what Collie's client package
//! defines.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use serde_json::Value;

use goodfetch_protocol::catalog::Product;

use super::layer::{Deprecation, Layer, Stability};
use super::naming::{pascal, snake};
use super::{Generated, TypesFile};

/// Collie's generated layer, as Foxhound's layer imports it.
const CLIENT_PACKAGE: &str = "goodfetch_collie_client.generated";

/// How `xtask codegen` runs `datamodel-code-generator`.
pub(super) const DATAMODEL_CODEGEN_OPTIONS: [&str; 13] = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.11",
    "--disable-timestamp",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-schema-description",
    "--use-field-description",
    "--use-annotated",
    "--field-constraints",
];

const EXPERIMENTAL: &str = "Experimental: outside semver until it is promoted (ADR 0030).";

pub(super) fn generate(layer: &Layer) -> Generated {
    let (mut input, _) = layer.generator_input(&format!("{}Types", layer.product.name()), |name| {
        ("customTypePath", format!("{CLIENT_PACKAGE}.models.{name}"))
    });
    allow_unknown_fields(&mut input);
    Generated {
        files: vec![
            ("__init__.py", init(layer)),
            ("operations.py", operations(layer)),
            ("events.py", events(layer)),
            ("errors.py", errors(layer)),
            ("plugins.py", plugins(layer)),
        ],
        types: TypesFile {
            output: "models.py",
            input,
            prefix: String::new(),
        },
    }
}

/// States JSON Schema's own default, that an object without
/// `additionalProperties` allows unknown fields, on every such object, so
/// `datamodel-code-generator` writes `extra='allow'` for it: the types the
/// engine sends keep what the SDK does not know in `model_extra`, while
/// those a program sends say `false` and forbid it (ADR 0082).
fn allow_unknown_fields(schema: &mut Value) {
    match schema {
        Value::Object(object) => {
            if object.get("type").and_then(Value::as_str) == Some("object")
                && !object.contains_key("additionalProperties")
            {
                object.insert("additionalProperties".to_owned(), Value::Bool(true));
            }
            for child in object.values_mut() {
                allow_unknown_fields(child);
            }
        }
        Value::Array(items) => items.iter_mut().for_each(allow_unknown_fields),
        _ => {}
    }
}

/// A module docstring and the imports every module opens with.
fn header(summary: &str) -> String {
    format!(
        "\"\"\"{summary}\n\nGenerated by `xtask codegen` from the catalog; never edit by hand.\n\"\"\"\n\nfrom __future__ import annotations\n"
    )
}

/// The import lines of the models `names`: the layer's own from `.models`,
/// Collie's from the client package.
fn model_imports(layer: &Layer, names: &BTreeSet<String>) -> String {
    let (collie, own): (Vec<&String>, Vec<&String>) =
        names.iter().partition(|name| layer.is_collie_type(name));
    let mut text = String::new();
    if !collie.is_empty() {
        let _ = writeln!(
            text,
            "from {CLIENT_PACKAGE}.models import {}",
            join(&collie)
        );
    }
    if !own.is_empty() {
        let _ = writeln!(text, "from .models import {}", join(&own));
    }
    text
}

fn join(names: &[&String]) -> String {
    names
        .iter()
        .map(|name| name.as_str())
        .collect::<Vec<_>>()
        .join(", ")
}

fn escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"")
}

/// A docstring, indented by `indent`.
fn docstring(
    indent: &str,
    description: &str,
    stability: Stability,
    deprecated: Option<&Deprecation>,
) -> String {
    let mut paragraphs = vec![escape(description)];
    if stability == Stability::Experimental {
        paragraphs.push(EXPERIMENTAL.to_owned());
    }
    if let Some(deprecated) = deprecated {
        paragraphs.push(format!(
            "Deprecated since {}: {}",
            deprecated.since,
            escape(&deprecated.note)
        ));
    }
    if paragraphs.len() == 1 {
        return format!("{indent}\"\"\"{}\"\"\"\n", paragraphs[0]);
    }
    let body = paragraphs
        .iter()
        .flat_map(|paragraph| paragraph.lines())
        .collect::<Vec<_>>();
    let mut text = format!("{indent}\"\"\"{}\n", body[0]);
    for paragraph in &paragraphs[1..] {
        let _ = writeln!(text);
        for line in paragraph.lines() {
            let _ = writeln!(text, "{indent}{line}");
        }
    }
    let _ = writeln!(text, "{indent}\"\"\"");
    text
}

fn deprecation_message(deprecated: &Deprecation) -> String {
    format!("Since {}: {}", deprecated.since, deprecated.note)
}

fn init(layer: &Layer) -> String {
    header(&format!(
        "The layer generated from {}'s entries of the catalog (ADR 0095).",
        layer.product.name()
    ))
}

fn operations(layer: &Layer) -> String {
    let product = layer.product.name();
    let types: BTreeSet<String> = layer
        .operations
        .iter()
        .flat_map(|operation| [operation.params.0.clone(), operation.result.0.clone()])
        .collect();
    let deprecates = layer
        .operations
        .iter()
        .any(|operation| operation.deprecated.is_some());
    let mut text = header(&format!(
        "{product}'s operations, each an async method and a sync one (ADR 0038)."
    ));
    text.push('\n');
    // In isort's order: classes, then functions.
    let returns = !layer.operations.is_empty();
    let typing: Vec<&str> = [
        ("Any", returns),
        ("Protocol", layer.product == Product::Collie),
        ("cast", returns),
    ]
    .into_iter()
    .filter_map(|(name, imported)| imported.then_some(name))
    .collect();
    if !typing.is_empty() {
        let _ = writeln!(text, "from typing import {}", typing.join(", "));
    }
    if layer.product == Product::Collie {
        text.push_str("\nfrom pydantic import BaseModel\n");
    }
    if deprecates {
        text.push_str("from typing_extensions import deprecated\n");
    }
    if layer.product == Product::Foxhound {
        let _ = writeln!(
            text,
            "\nfrom {CLIENT_PACKAGE}.operations import AsyncCaller, Caller"
        );
    }
    let imports = model_imports(layer, &types);
    if !imports.is_empty() {
        text.push('\n');
        text.push_str(&imports);
    }
    if layer.product == Product::Collie {
        text.push_str(CALLERS);
    }
    if !layer.operations.is_empty() {
        text.push_str(FIELDS);
    }
    for (prefix, caller, asynchronous) in [("Async", "AsyncCaller", true), ("", "Caller", false)] {
        let mode = if asynchronous { "async" } else { "sync" };
        let _ = write!(
            text,
            "\n\nclass {prefix}{product}Operations:\n    \"\"\"{product}'s operations, each a{} {mode} method.\"\"\"\n\n    def __init__(self, caller: {caller}) -> None:\n        \"\"\"Takes the runtime that sends each call.\"\"\"\n        self._caller = caller\n",
            if asynchronous { "n" } else { "" }
        );
        for operation in &layer.operations {
            text.push('\n');
            if let Some(deprecated) = &operation.deprecated {
                let _ = writeln!(
                    text,
                    "    @deprecated({:?})",
                    deprecation_message(deprecated)
                );
            }
            let (params, result) = (&operation.params.0, &operation.result.0);
            let _ = writeln!(
                text,
                "    {}def {}(self, params: {params}) -> {result}:",
                if asynchronous { "async " } else { "" },
                snake(&operation.name)
            );
            text.push_str(&docstring(
                "        ",
                &operation.description,
                operation.stability,
                operation.deprecated.as_ref(),
            ));
            let _ = writeln!(
                text,
                "        return {result}.model_construct(**_fields({}self._caller.call({:?}, params)))",
                if asynchronous { "await " } else { "" },
                operation.name
            );
        }
    }
    text
}

/// What Collie's client package declares once for every layer's methods.
const CALLERS: &str = r#"

class AsyncCaller(Protocol):
    """What sends a call for the async methods: the client package's runtime."""

    async def call(self, operation: str, params: BaseModel) -> object:
        """Sends one call and returns its result as the engine sent it."""
        ...


class Caller(Protocol):
    """What sends a call for the sync methods: the client package's runtime."""

    def call(self, operation: str, params: BaseModel) -> object:
        """Sends one call and returns its result as the engine sent it."""
        ...
"#;

/// How each method builds its result: from the fields as the engine sent
/// them, without validation, so a field or value a newer engine added never
/// raises (ADR 0082).
const FIELDS: &str = r#"

def _fields(result: object) -> dict[str, Any]:
    """The fields of a result, the JSON object the engine sent."""
    return cast("dict[str, Any]", result)
"#;

fn events(layer: &Layer) -> String {
    let product = layer.product.name();
    let types: BTreeSet<String> = layer
        .events
        .iter()
        .map(|event| event.payload.0.clone())
        .collect();
    let mut text = header(&format!("The registry of {product}'s events (ADR 0038)."));
    text.push_str("\nfrom collections.abc import Mapping\nfrom typing import Final\n\nfrom pydantic import BaseModel\n");
    let imports = model_imports(layer, &types);
    if !imports.is_empty() {
        text.push('\n');
        text.push_str(&imports);
    }
    text.push_str("\nEVENTS: Final[Mapping[str, type[BaseModel]]] = {\n");
    for event in &layer.events {
        let _ = writeln!(text, "    {:?}: {},", event.name, event.payload.0);
    }
    text.push_str("}\n\"\"\"The payload type of each event");
    if layer.events.is_empty() {
        text.push_str(".\"\"\"\n");
    } else {
        text.push_str(":\n\n");
        for event in &layer.events {
            let _ = writeln!(
                text,
                "- `{}`: {}",
                event.name,
                escape(&event.description).replace('\n', " ")
            );
        }
        text.push_str("\"\"\"\n");
    }
    text.push_str("\nEXPERIMENTAL_EVENTS: Final[frozenset[str]] = frozenset({\n");
    for event in &layer.events {
        if event.stability == Stability::Experimental {
            let _ = writeln!(text, "    {:?},", event.name);
        }
    }
    text.push_str(
        "})\n\"\"\"The events outside semver until they are promoted (ADR 0030).\"\"\"\n",
    );
    text.push_str("\nDEPRECATED_EVENTS: Final[Mapping[str, str]] = {\n");
    for event in &layer.events {
        if let Some(deprecated) = &event.deprecated {
            let _ = writeln!(
                text,
                "    {:?}: {:?},",
                event.name,
                deprecation_message(deprecated)
            );
        }
    }
    text.push_str("}\n\"\"\"Each deprecated event, with its deprecation.\"\"\"\n");
    text
}

fn group_class(group: &str) -> String {
    format!("{}Error", pascal(group))
}

fn errors(layer: &Layer) -> String {
    let product = layer.product.name();
    let mut text = header(&format!(
        "The exception class of each of {product}'s Error codes (ADR 0079)."
    ));
    text.push_str("\nfrom collections.abc import Callable, Mapping\nfrom typing import Final");
    match layer.product {
        Product::Collie => {
            text.push_str(", Literal\n\nErrorGroup = Literal[");
            text.push_str(
                &layer
                    .error_groups
                    .iter()
                    .map(|group| format!("{:?}", group.name))
                    .collect::<Vec<_>>()
                    .join(", "),
            );
            text.push_str(
                "]\n\"\"\"The seven groups of Error codes, named for their remedy.\"\"\"\n",
            );
            text.push_str(GOODFETCH_ERROR);
            for group in &layer.error_groups {
                let _ = write!(
                    text,
                    "\n\nclass {}(GoodfetchError):\n",
                    group_class(&group.name)
                );
                text.push_str(&docstring(
                    "    ",
                    &group.description,
                    Stability::Stable,
                    None,
                ));
            }
        }
        Product::Foxhound => {
            let mut imported: BTreeSet<String> = layer
                .error_codes
                .iter()
                .map(|code| group_class(&code.group))
                .collect();
            imported.insert("GoodfetchError".to_owned());
            let names: Vec<&String> = imported.iter().collect();
            let _ = writeln!(
                text,
                "\n\nfrom {CLIENT_PACKAGE}.errors import {}",
                join(&names)
            );
        }
    }
    let mut registry = Vec::new();
    for code in &layer.error_codes {
        let group = group_class(&code.group);
        if code.name == code.group {
            registry.push((code.name.clone(), group));
            continue;
        }
        let class = format!("{}Error", pascal(&code.name));
        let _ = write!(text, "\n\nclass {class}({group}):\n");
        text.push_str(&docstring(
            "    ",
            &code.description,
            Stability::Stable,
            None,
        ));
        let _ = write!(
            text,
            "\n    def __init__(self, message: str) -> None:\n        \"\"\"Takes the message the engine rendered.\"\"\"\n        super().__init__(message, code={:?}, group={:?}, retryable={})\n",
            code.name,
            code.group,
            if code.retryable { "True" } else { "False" }
        );
        registry.push((code.name.clone(), class));
    }
    text.push_str("\n\nERROR_CLASSES: Final[Mapping[str, Callable[[str], GoodfetchError]]] = {\n");
    for (code, class) in registry {
        let _ = writeln!(text, "    {code:?}: {class},");
    }
    text.push_str("}\n\"\"\"The exception class of each Error code.\"\"\"\n");
    text
}

/// The base of every exception class, generated once in Collie's client package.
const GOODFETCH_ERROR: &str = r#"

class GoodfetchError(Exception):
    """The base of every error a Goodfetch SDK raises (ADR 0079)."""

    code: str
    """The Error code, as the engine sent it."""
    group: ErrorGroup
    """The code's group, named for its remedy."""
    retryable: bool
    """Whether the same call may succeed when made again."""

    def __init__(self, message: str, *, code: str, group: ErrorGroup, retryable: bool) -> None:
        """Takes the message and the code's fields."""
        super().__init__(message)
        self.code = code
        self.group = group
        self.retryable = retryable
"#;

fn plugins(layer: &Layer) -> String {
    let product = layer.product.name();
    let types: BTreeSet<String> = layer
        .plugin_kinds
        .iter()
        .flat_map(|kind| &kind.methods)
        .flat_map(|method| [method.params.0.clone(), method.result.0.clone()])
        .collect();
    let mut text = header(&format!(
        "The base classes of SDK handlers for each of {product}'s Plugin kinds (ADR 0033)."
    ));
    if layer.plugin_kinds.is_empty() {
        return text;
    }
    text.push_str("\nfrom abc import ABC, abstractmethod\n");
    let imports = model_imports(layer, &types);
    if !imports.is_empty() {
        text.push('\n');
        text.push_str(&imports);
    }
    for kind in &layer.plugin_kinds {
        let _ = write!(text, "\n\nclass {}Handler(ABC):\n", pascal(&kind.name));
        text.push_str(&docstring("    ", &kind.description, kind.stability, None));
        for method in &kind.methods {
            let _ = write!(
                text,
                "\n    @abstractmethod\n    async def {}(self, params: {}) -> {}:\n",
                snake(&method.name),
                method.params.0,
                method.result.0
            );
            text.push_str(&docstring(
                "        ",
                &method.description,
                Stability::Stable,
                None,
            ));
        }
    }
    text
}
