/// The folder of the generated handles.
pub(super) const FOLDER: &str = "crates/goodfetch-collie-client/src/generated";

/// The client crate's manifest: without it, the workspace has no Rust
/// client to generate into.
const MANIFEST: &str = "crates/goodfetch-collie-client/Cargo.toml";

const HEADER: &str = "// Generated by `xtask codegen` from the catalog: never edit by hand.\n";

const EXPERIMENTAL: &str = "Experimental: outside semver until it is promoted (ADR 0030).";

/// The `# Errors` section of a member that answers through a call
/// (STYLE.md, Documentation in code).
const CALL_ERRORS: &str = "# Errors\n\nOnce sent, `closed` when its handle or the Connection is closed, the engine's error, `deadline_exceeded` once its timeout runs out, and `internal` when its reply does not fit its type.";

/// The `# Errors` section of a member that answers through a query, which
/// takes no timeout.
const QUERY_ERRORS: &str = "# Errors\n\nOnce sent, `closed` when its handle or the Connection is closed, the engine's error, and `internal` when its answer does not fit its type.";

/// The parameter a call sends its own timeout in (ADR 0080).
const TIMEOUT: &str = "timeout";

/// The member names a handle already uses: its ID and the field it reaches
/// its engine through, in either twin.
const HANDLE_NAMES: [&str; 4] = ["host", "id", "inner", "new"];

/// The methods `Call` and `Query` already have, which no option may
/// shadow.
const BUILDER_NAMES: [&str; 10] = [
    "edit",
    "into_future",
    "map",
    "new",
    "no_timeout",
    "send",
    TIMEOUT,
    "try_map",
    "typed",
    "wire_timeout",
];

/// The protocol's response to a page's request, which a member answers as
/// the crate's `Response` (ADR 0085).
const PAGE_RESPONSE: &str = "::goodfetch_protocol::page::PageResponse";

/// The protocol's request a page sent and the response it got, which a
/// member answers as the crate's `Exchange`, its response a `Response`.
const PAGE_EXCHANGE: &str = "::goodfetch_protocol::page::events::PageExchange";

/// The ID of the page a `Response` reads its body through.
const PAGE_ID: &str = "::goodfetch_protocol::page::PageId";

/// Collie's Rust handles, `handles.rs`, `blocking.rs`, `events.rs` and
/// `settings.rs` under [`FOLDER`], or nothing when the workspace has no
/// Rust client.
pub(super) fn generate(root: &Path, layer: &Layer) -> Result<BTreeMap<String, Vec<u8>>> {
    if !root.join(MANIFEST).is_file() {
        return Ok(BTreeMap::new());
    }
    let index = Index::read(root)?.context(
        "the Rust client's handles name `goodfetch-protocol`'s types, which the workspace lacks",
    )?;
    let handles = handles::handles(layer)?;
    let mut asynchronous = Module::new(Twin::Async);
    let mut blocking = Module::new(Twin::Blocking);
    let mut listeners = Vec::new();
    for handle in &handles {
        let model = HandleModel::new(&index, layer, handle)?;
        asynchronous.handle(&model);
        blocking.handle(&model);
        listeners.extend(model.listener);
    }
    let mut files = BTreeMap::new();
    files.insert(
        format!("{FOLDER}/handles.rs"),
        rustfmt(&asynchronous.text()).context("formatting the Rust handles")?,
    );
    files.insert(
        format!("{FOLDER}/blocking.rs"),
        rustfmt(&blocking.text()).context("formatting the blocking Rust handles")?,
    );
    files.insert(
        format!("{FOLDER}/events.rs"),
        rustfmt(&listeners::module(HEADER, &listeners))
            .context("formatting the Rust events' markers")?,
    );
    files.insert(
        format!("{FOLDER}/settings.rs"),
        rustfmt(&settings::module(HEADER, &layer.settings)?)
            .context("formatting the Rust settings' keys")?,
    );
    Ok(files)
}

/// A parameter a member takes positionally.
struct Positional {
    ident: String,
    /// Its type in the member's signature.
    declared: String,
}

/// The parameters `positional` declares, each after a comma, as a
/// signature lists them after `&self`.
fn declared(positional: &[Positional]) -> String {
    positional
        .iter()
        .fold(String::new(), |mut declared, positional| {
            let _ = write!(declared, ", {}: {}", positional.ident, positional.declared);
            declared
        })
}

/// A builder method that sets one named parameter of a params type.
struct Setter {
    doc: String,
    declared: String,
    /// The value the field takes, from the argument named `ident`.
    set: String,
    /// The scope whose settings the member opens, which a `settings` option
    /// checks its keys against: the variant of `SettingScope`.
    scope: Option<String>,
}

/// Which builder a member returns.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Builds {
    Call,
    Query,
}

impl Builds {
    /// The builder a member of `form` returns.
    fn of(form: &Form) -> Self {
        if *form == Form::Query {
            Self::Query
        } else {
            Self::Call
        }
    }

    fn name(self) -> &'static str {
        match self {
            Self::Call => "Call",
            Self::Query => "Query",
        }
    }
}

/// A member, its signature and its params resolved against the protocol
/// crate.
struct MemberModel {
    ident: String,
    doc: String,
    deprecated: Option<String>,
    /// ADR 0030's run-time warning of its markers, which it opens with.
    warning: Option<String>,
    form: Form,
    method: String,
    params: String,
    result: String,
    positional: Vec<Positional>,
    /// The struct literal of its params, every field set.
    literal: String,
    /// Whether the builder sends its timeout in the params (ADR 0080).
    wire_timeout: bool,
    /// What it answers of its result.
    answers: Answers,
    /// Whether what it answers is a page's response, which it wraps.
    responds: Responds,
}

/// Whether a member answers a page's response, which it answers as the
/// crate's `Response`, or a request with its response, which it answers
/// as the crate's `Exchange`.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Responds {
    /// It answers something else.
    No,
    /// It answers a `PageResponse`.
    Always,
    /// It answers an optional `PageResponse`.
    Optionally,
    /// It answers a `PageExchange`.
    Exchanged,
}

impl Responds {
    /// Whether `answered`, the type a member answers, is a page's
    /// response.
    fn of(answered: &str) -> Self {
        if answered == PAGE_RESPONSE {
            Self::Always
        } else if answered == format!("Option<{PAGE_RESPONSE}>") {
            Self::Optionally
        } else if answered == PAGE_EXCHANGE {
            Self::Exchanged
        } else {
            Self::No
        }
    }

    /// The type a member answers once a response is wrapped, as `twin`
    /// spells it: `answered` itself when it is not one.
    fn answered(self, answered: String, twin: Twin) -> String {
        match self {
            Self::No => answered,
            Self::Always => format!("{}::Response", twin.builders()),
            Self::Optionally => format!("Option<{}::Response>", twin.builders()),
            Self::Exchanged => format!("{}::Exchange", twin.builders()),
        }
    }

    /// An async member's answer, `value`, wrapped: each response with the
    /// page's `host`.
    fn wrapped(self, value: &str) -> String {
        match self {
            Self::No => value.to_owned(),
            Self::Always => format!("crate::Response::new(host, {value})"),
            Self::Optionally => {
                format!("{value}.map(|response| crate::Response::new(host, response))")
            }
            Self::Exchanged => format!("crate::Exchange::new(host, {value})"),
        }
    }

    /// The function from an async member's answer to its blocking twin's.
    fn blocking(self) -> &'static str {
        match self {
            Self::No => "",
            Self::Always => "crate::blocking::Response::new",
            Self::Optionally => "|answered| answered.map(crate::blocking::Response::new)",
            Self::Exchanged => "crate::blocking::Exchange::new",
        }
    }
}

/// What a member answers of its operation's result.
enum Answers {
    /// The result itself.
    Result,
    /// For an opener: the handle it opens, and the result field of its ID
    /// that the handle carries.
    Opened { handle: String, carried: String },
    /// For a result of one property (issue 2517): that field's type and
    /// ident, its value answered in place of the result.
    Field { ty: String, ident: String },
}

impl MemberModel {
    fn builds(&self) -> Builds {
        Builds::of(&self.form)
    }

    /// Its return type, as `twin` spells it.
    fn returns(&self, twin: Twin) -> String {
        let answered = match (&self.form, &self.answers) {
            (Form::Closes, _) => "()".to_owned(),
            (_, Answers::Opened { handle, .. }) => handle.clone(),
            (_, Answers::Field { ty, .. }) => ty.clone(),
            // A whole result keeps the JSON it came from, the fields this
            // SDK does not know included, readable through `raw()` (ADR 0082).
            (_, Answers::Result) if self.responds == Responds::No => {
                format!("crate::Answer<{}>", self.result)
            }
            (_, Answers::Result) => self.result.clone(),
        };
        let answered = self.responds.answered(answered, twin);
        format!(
            "{}::{}<{answered}, {}>",
            twin.builders(),
            self.builds().name(),
            self.params
        )
    }

    fn declared(&self) -> String {
        declared(&self.positional)
    }

    fn forwarded(&self) -> String {
        self.positional
            .iter()
            .map(|positional| positional.ident.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    }
}

struct BuilderModel {
    ident: String,
    handle: String,
    doc: String,
    positional: Vec<Positional>,
    literal: String,
}

struct SubObjectModel {
    ident: String,
    type_name: String,
    members: Vec<MemberModel>,
}

/// A handle, resolved against the protocol crate.
struct HandleModel {
    namespace: &'static str,
    type_name: String,
    id: String,
    /// The parameter its ID fills, such as `page_id`.
    param: String,
    members: Vec<MemberModel>,
    builders: Vec<BuilderModel>,
    sub_objects: Vec<SubObjectModel>,
    /// Its `events`, when it has a listener.
    listener: Option<ListenerModel>,
    /// The setters each builder of each params type gains.
    setters: BTreeMap<(Builds, String), BTreeMap<String, Setter>>,
}

impl HandleModel {
    fn new(index: &Index, layer: &Layer, handle: &Handle<'_>) -> Result<Self> {
        let type_name = type_name(handle.namespace)?;
        let id = index.type_path(&handle.id.type_name)?;
        let mut setters = BTreeMap::new();
        let mut members = Vec::new();
        for member in &handle.members {
            members.push(member_model(
                index,
                layer,
                member,
                &handle.id,
                &mut setters,
            )?);
        }
        let mut builders = Vec::new();
        for built in &handle.builders {
            builders.push(builder_model(index, built, &handle.id)?);
        }
        let mut sub_objects = Vec::new();
        for sub_object in &handle.sub_objects {
            let mut held = Vec::new();
            for member in &sub_object.members {
                held.push(member_model(
                    index,
                    layer,
                    member,
                    &handle.id,
                    &mut setters,
                )?);
            }
            sub_objects.push(SubObjectModel {
                ident: ident(
                    sub_object.name,
                    &format!("sub-object `{}`", sub_object.name),
                )?,
                type_name: format!("{type_name}{}", self::type_name(sub_object.name)?),
                members: held,
            });
        }
        Ok(Self {
            namespace: handle.namespace,
            type_name,
            id,
            param: handle.id.param.clone(),
            members,
            builders,
            sub_objects,
            listener: ListenerModel::new(index, handle)?,
            setters,
        })
    }
}

fn type_name(namespace: &str) -> Result<String> {
    rust_type(namespace).with_context(|| format!("`{namespace}` is no Rust type name"))
}

fn ident(name: &str, what: &str) -> Result<String> {
    if HANDLE_NAMES.contains(&name) {
        bail!("{what}: a Rust handle already has a `{name}`, so the catalog renames it (ADR 0099)");
    }
    rust_snake(name).with_context(|| format!("{what}: `{name}` is no Rust name (ADR 0099)"))
}

/// The doc comment of an entry: its description, a paragraph for each
/// marker it carries, then its `errors` section.
fn doc(
    description: &str,
    stability: Stability,
    deprecated: Option<&Deprecation>,
    errors: &str,
) -> String {
    let mut paragraphs = vec![description.trim().to_owned()];
    if stability == Stability::Experimental {
        paragraphs.push(EXPERIMENTAL.to_owned());
    }
    if let Some(deprecated) = deprecated {
        paragraphs.push(format!("Deprecated. {}", deprecated.message()));
    }
    paragraphs.push(errors.to_owned());
    comment(&paragraphs.join("\n\n"))
}

/// The statement a member of the entry `name` opens with: ADR 0030's
/// run-time warning of each marker it carries, once per process, or `None`
/// for a stable entry that is not deprecated.
fn warning(name: &str, stability: Stability, deprecated: Option<&Deprecation>) -> Option<String> {
    let experimental = stability == Stability::Experimental;
    if !experimental && deprecated.is_none() {
        return None;
    }
    let deprecation = deprecated.map_or_else(
        || "None".to_owned(),
        |deprecated| format!("Some({:?})", deprecated.message()),
    );
    Some(format!(
        "crate::markers::warn({name:?}, {experimental}, {deprecation});"
    ))
}

/// `text` as `///` lines.
fn comment(text: &str) -> String {
    text.lines().fold(String::new(), |mut comment, line| {
        if line.is_empty() {
            comment.push_str("///\n");
        } else {
            let _ = writeln!(comment, "/// {line}");
        }
        comment
    })
}

/// The parameter `name`'s field of `fields`.
fn field<'a>(fields: &'a [Field], name: &str, owner: &str) -> Result<&'a Field> {
    fields
        .iter()
        .find(|field| field.wire == name)
        .with_context(|| {
            format!("{owner}: its params type has no field for the parameter `{name}`")
        })
}

/// The positional parameters of `parameters` and the struct literal of
/// `params` that sets the handle's ID, each positional one by its argument
/// and every other field to its default.
fn literal(
    index: &Index,
    params: &str,
    parameters: &Parameters,
    id: &HandleId,
    owner: &str,
) -> Result<(Vec<Positional>, String)> {
    let fields = index
        .fields(params)
        .with_context(|| format!("{owner}: reading its params type `{params}`"))?;
    for name in parameters
        .positional
        .iter()
        .chain(&parameters.named)
        .chain(&parameters.optional)
        .chain([&id.param])
    {
        field(&fields, name, owner)?;
    }
    let mut positional = Vec::new();
    let mut entries = Vec::new();
    for field in &fields {
        if field.wire == id.param {
            entries.push(format!("{}: self.host.id().clone()", field.ident));
        } else if parameters.positional.contains(&field.wire) {
            let (declared, passed) = if field.ty == "String" {
                (
                    "impl Into<String>".to_owned(),
                    format!("{}.into()", field.ident),
                )
            } else {
                (field.ty.clone(), field.ident.clone())
            };
            entries.push(if passed == field.ident {
                passed
            } else {
                format!("{}: {passed}", field.ident)
            });
            positional.push(Positional {
                ident: field.ident.clone(),
                declared,
            });
        } else if field.ty.starts_with("Option<") {
            entries.push(format!("{}: None", field.ident));
        } else if field.ty == "bool" {
            entries.push(format!("{}: false", field.ident));
        } else {
            entries.push(format!("{}: <{}>::default()", field.ident, field.ty));
        }
    }
    let path = index.type_path(params)?;
    Ok((positional, format!("{path} {{ {} }}", entries.join(", "))))
}

/// The setter of the named parameter `field`: its argument's type and the
/// value the field takes.
fn setter(field: &Field, doc: String) -> Setter {
    let ident = field.ident.clone();
    let ty = field.ty.as_str();
    let (declared, set) = if ty == "String" {
        ("impl Into<String>".to_owned(), format!("{ident}.into()"))
    } else if ty == "Option<String>" {
        (
            "impl Into<String>".to_owned(),
            format!("Some({ident}.into())"),
        )
    } else if let Some(inner) = ty
        .strip_prefix("Option<")
        .and_then(|inner| inner.strip_suffix('>'))
    {
        // `Option<Option<X>>` takes `Option<X>`: `None` sends null.
        (inner.to_owned(), format!("Some({ident})"))
    } else {
        (ty.to_owned(), ident.clone())
    };
    Setter {
        doc,
        declared,
        set,
        scope: None,
    }
}

fn member_model(
    index: &Index,
    layer: &Layer,
    member: &Member<'_>,
    id: &HandleId,
    setters: &mut BTreeMap<(Builds, String), BTreeMap<String, Setter>>,
) -> Result<MemberModel> {
    let operation = member.operation;
    let owner = format!("operation `{}`", operation.name);
    let params_name = &operation.params.0;
    let (positional, literal) = literal(index, params_name, &member.parameters, id, &owner)?;
    let params = index.type_path(params_name)?;
    let result = index.type_path(&operation.result.0)?;
    let parameters = &member.parameters;
    if parameters
        .positional
        .iter()
        .chain(&parameters.named)
        .any(|name| name == TIMEOUT)
    {
        bail!("{owner}: a call's `timeout` is optional, which the builder sends (ADR 0080)");
    }
    let wire_timeout =
        member.form != Form::Query && parameters.optional.iter().any(|name| name == TIMEOUT);
    let builds = Builds::of(&member.form);
    let fields = index.fields(params_name)?;
    let schema = layer.definitions.get(params_name);
    let own = setters.entry((builds, params.clone())).or_default();
    for name in parameters
        .named
        .iter()
        .chain(&parameters.optional)
        .filter(|name| *name != TIMEOUT)
    {
        let field = field(&fields, name, &owner)?;
        if BUILDER_NAMES.contains(&field.ident.as_str()) {
            bail!(
                "{owner}: its parameter `{name}` would shadow the builder's own `{name}`, so the catalog renames it (ADR 0099)"
            );
        }
        let description = schema
            .and_then(|schema| schema["properties"][name.as_str()]["description"].as_str())
            .map_or_else(|| format!("Sets `{name}`."), str::to_owned);
        let made = settings::setter(member, name, &description, &owner)?
            .unwrap_or_else(|| setter(field, comment(&description)));
        own.entry(field.ident.clone()).or_insert(made);
    }
    let answers = match (&member.form, &member.unwrapped) {
        (Form::Opens(opened), _) => {
            let results = index.fields(&operation.result.0)?;
            let carried = field(&results, &format!("{opened}_id"), &owner)?;
            Answers::Opened {
                handle: type_name(opened)?,
                carried: carried.ident.clone(),
            }
        }
        (_, Some(unwrapped)) => {
            let results = index.fields(&operation.result.0)?;
            let answered = field(&results, &unwrapped.property, &owner)?;
            Answers::Field {
                ty: answered.ty.clone(),
                ident: answered.ident.clone(),
            }
        }
        (_, None) => Answers::Result,
    };
    let responds = responds(index, member, id, &answers, &result, &owner)?;
    Ok(MemberModel {
        ident: ident(member.name, &owner)?,
        doc: doc(
            &operation.description,
            operation.stability,
            operation.deprecated.as_ref(),
            match builds {
                Builds::Call => CALL_ERRORS,
                Builds::Query => QUERY_ERRORS,
            },
        ),
        warning: warning(
            &operation.name,
            operation.stability,
            operation.deprecated.as_ref(),
        ),
        deprecated: operation.deprecated.as_ref().map(|deprecated| {
            format!(
                "#[deprecated(since = {:?}, note = {:?})]\n",
                deprecated.since.to_string(),
                deprecated.message()
            )
        }),
        form: match &member.form {
            Form::RoundTrip => Form::RoundTrip,
            Form::Query => Form::Query,
            Form::Waiter => Form::Waiter,
            Form::Opens(opened) => Form::Opens(opened.clone()),
            Form::Closes => Form::Closes,
        },
        method: operation.name.clone(),
        params,
        result,
        positional,
        literal,
        wire_timeout,
        answers,
        responds,
    })
}

/// Whether `member` of the handle `id`, whose answer is `answers` of the
/// result type `result`, answers a page's response, which its Rust form
/// wraps in the `Response` that reads its body.
fn responds(
    index: &Index,
    member: &Member<'_>,
    id: &HandleId,
    answers: &Answers,
    result: &str,
    owner: &str,
) -> Result<Responds> {
    let responds = Responds::of(match answers {
        Answers::Field { ty, .. } => ty,
        Answers::Opened { .. } => "",
        Answers::Result => result,
    });
    if responds != Responds::No {
        if member.form == Form::Query {
            bail!("{owner}: a query answers no page's response, which a call reads the body of");
        }
        if index.type_path(&id.type_name)? != PAGE_ID {
            bail!(
                "{owner}: only a page's member answers a response, which reads its body through the page"
            );
        }
    }
    Ok(responds)
}

fn builder_model(index: &Index, built: &Builder, id: &HandleId) -> Result<BuilderModel> {
    let owner = format!("the value `{}` a handle builds", built.builds);
    if !(built.parameters.named.is_empty() && built.parameters.optional.is_empty()) {
        bail!("{owner}: a value built without a call takes only positional parameters in Rust");
    }
    let (positional, literal) = literal(index, &built.type_name, &built.parameters, id, &owner)?;
    Ok(BuilderModel {
        ident: ident(&built.builds, &owner)?,
        handle: type_name(&built.builds)?,
        doc: comment(&format!(
            "{}\n\nBuilt without a call (ADR 0099).",
            built.description.trim()
        )),
        positional,
        literal,
    })
}

/// One of the two modules: the async handles or their blocking twins.
#[derive(Clone, Copy)]
enum Twin {
    Async,
    Blocking,
}

impl Twin {
    /// The module of the builders its members return.
    fn builders(self) -> &'static str {
        match self {
            Self::Async => "crate",
            Self::Blocking => "crate::blocking",
        }
    }
}

struct Module {
    twin: Twin,
    body: String,
    /// The setters of each builder, each type's once.
    setters: BTreeMap<(Builds, String), BTreeMap<String, String>>,
}

impl Module {
    fn new(twin: Twin) -> Self {
        Self {
            twin,
            body: String::new(),
            setters: BTreeMap::new(),
        }
    }

    fn text(&self) -> String {
        let summary = match self.twin {
            Twin::Async => "//! The handles a program holds of Collie's values (ADR 0099).\n",
            Twin::Blocking => {
                "//! The blocking twins of the handles a program holds of Collie's values (ADR 0099), under the same names.\n"
            }
        };
        let mut text = format!("{HEADER}\n{summary}");
        text.push_str(&self.body);
        for ((builds, params), setters) in &self.setters {
            if setters.is_empty() {
                continue;
            }
            let _ = writeln!(
                text,
                "\nimpl<T> {}::{}<T, {params}> {{",
                self.twin.builders(),
                builds.name()
            );
            for setter in setters.values() {
                text.push_str(setter);
            }
            text.push_str("}\n");
        }
        text
    }

    /// The struct of a handle or sub-object, whose ID is `id`, and the
    /// head of its `impl`.
    fn open(&mut self, doc: &str, type_name: &str, id: &str) {
        let held = match self.twin {
            Twin::Async => format!("host: crate::host::Host<{id}>"),
            Twin::Blocking => format!("inner: crate::generated::handles::{type_name}"),
        };
        let _ = write!(
            self.body,
            "\n{doc}#[derive(Clone, Debug)]\npub struct {type_name} {{\n    pub(crate) {held},\n}}\n\nimpl {type_name} {{\n"
        );
    }

    fn handle(&mut self, model: &HandleModel) {
        for ((builds, params), setters) in &model.setters {
            let own = self.setters.entry((*builds, params.clone())).or_default();
            for (name, setter) in setters {
                own.entry(name.clone()).or_insert_with(|| {
                    let body = match &setter.scope {
                        Some(scope) => format!(
                            "self.try_edit(move |params| {{\n            params.{name} = {}.within(::goodfetch_protocol::catalog::SettingScope::{scope})?;\n            Ok(())\n        }})",
                            setter.set
                        ),
                        None => format!("self.edit(move |params| params.{name} = {})", setter.set),
                    };
                    format!(
                        "{}    pub fn {name}(self, {name}: {}) -> Self {{\n        {body}\n    }}\n",
                        indent(&setter.doc),
                        setter.declared,
                    )
                });
            }
        }
        for sub_object in &model.sub_objects {
            self.open(
                &comment(&format!(
                    "The `{}` of a `{}` (ADR 0099).",
                    sub_object.ident, model.namespace
                )),
                &sub_object.type_name,
                &model.id,
            );
            for member in &sub_object.members {
                self.member(member);
            }
            self.body.push_str("}\n");
        }
        self.open(
            &comment(&format!(
                "A `{}` a program holds: the members the catalog gives it (ADR 0099).",
                model.namespace
            )),
            &model.type_name,
            &model.id,
        );
        let id = match self.twin {
            Twin::Async => "self.host.id()",
            Twin::Blocking => "self.inner.id()",
        };
        let _ = write!(
            self.body,
            "    /// Its ID, which names it to the engine.\n    #[must_use]\n    pub fn id(&self) -> &{} {{\n        {id}\n    }}\n",
            model.id
        );
        self.body
            .push_str(&raw_call::member(self.twin, model.namespace, &model.param));
        for sub_object in &model.sub_objects {
            let held = match self.twin {
                Twin::Async => "host: self.host.clone()",
                Twin::Blocking => &format!("inner: self.inner.{}()", sub_object.ident),
            };
            let _ = write!(
                self.body,
                "\n    /// Its `{}`.\n    #[must_use]\n    pub fn {}(&self) -> {} {{\n        {} {{ {held} }}\n    }}\n",
                sub_object.ident, sub_object.ident, sub_object.type_name, sub_object.type_name
            );
        }
        for member in &model.members {
            self.member(member);
        }
        if let Some(listener) = &model.listener {
            self.body.push_str(&listener.member(self.twin));
        }
        for built in &model.builders {
            self.builder(built);
        }
        self.body.push_str("}\n");
        if let Some(listener) = &model.listener {
            self.body.push_str(&listener.values(self.twin));
        }
    }

    fn member(&mut self, member: &MemberModel) {
        let _ = write!(self.body, "\n{}", indent(&member.doc));
        if let Some(deprecated) = &member.deprecated {
            let _ = write!(self.body, "    {deprecated}");
            if matches!(self.twin, Twin::Blocking) {
                self.body.push_str(
                    "    #[expect(deprecated, reason = \"the twin of a deprecated member calls it\")]\n",
                );
            }
        }
        let _ = writeln!(
            self.body,
            "    pub fn {}(&self{}) -> {} {{",
            member.ident,
            member.declared(),
            member.returns(self.twin)
        );
        let body = match self.twin {
            Twin::Async => {
                let sent = format!("{:?}, {}", member.method, member.literal);
                let wire = if member.wire_timeout {
                    ".wire_timeout()"
                } else {
                    ""
                };
                match (&member.form, &member.answers) {
                    (Form::Closes, _) => format!("self.host.close({sent})"),
                    (Form::Query, Answers::Field { ident, .. }) => format!(
                        "let query: crate::Query<{}, {}> = self.host.query({sent});\n        query.map(|result| result.{ident})",
                        member.result, member.params
                    ),
                    (Form::Query, _) => format!("self.host.query({sent})"),
                    (_, Answers::Opened { handle, carried }) => format!(
                        "let host = self.host.clone();\n        let call: crate::Call<{}, {}> = self.host.call({sent});\n        call{wire}.map(move |opened| {handle} {{ host: host.child(opened.{carried}) }})",
                        member.result, member.params
                    ),
                    (_, Answers::Field { ident, .. }) if member.responds != Responds::No => {
                        format!(
                            "let host = self.host.clone();\n        let call: crate::Call<{}, {}> = self.host.call({sent});\n        call{wire}.map(move |result| {})",
                            member.result,
                            member.params,
                            member.responds.wrapped(&format!("result.{ident}"))
                        )
                    }
                    (_, Answers::Field { ident, .. }) => format!(
                        "let call: crate::Call<{}, {}> = self.host.call({sent});\n        call{wire}.map(|result| result.{ident})",
                        member.result, member.params
                    ),
                    (_, Answers::Result) if member.responds != Responds::No => format!(
                        "let host = self.host.clone();\n        let call: crate::Call<{}, {}> = self.host.call({sent});\n        call{wire}.map(move |result| {})",
                        member.result,
                        member.params,
                        member.responds.wrapped("result")
                    ),
                    (_, Answers::Result) => format!("self.host.call({sent}){wire}"),
                }
            }
            Twin::Blocking => {
                let mut built = format!("self.inner.{}({})", member.ident, member.forwarded());
                if let Answers::Opened { handle, .. } = &member.answers {
                    let _ = write!(built, ".map(|inner| {handle} {{ inner }})");
                }
                if member.responds != Responds::No {
                    let _ = write!(built, ".map({})", member.responds.blocking());
                }
                format!(
                    "crate::blocking::{}::new({built}, self.inner.host.connection())",
                    member.builds().name()
                )
            }
        };
        if let (Twin::Async, Some(warning)) = (self.twin, &member.warning) {
            let _ = writeln!(self.body, "        {warning}");
        }
        let _ = writeln!(self.body, "        {body}\n    }}");
    }

    fn builder(&mut self, built: &BuilderModel) {
        let declared = declared(&built.positional);
        let body = match self.twin {
            Twin::Async => format!(
                "{} {{ host: self.host.child({}) }}",
                built.handle, built.literal
            ),
            Twin::Blocking => {
                let forwarded: Vec<&str> = built
                    .positional
                    .iter()
                    .map(|positional| positional.ident.as_str())
                    .collect();
                format!(
                    "{} {{ inner: self.inner.{}({}) }}",
                    built.handle,
                    built.ident,
                    forwarded.join(", ")
                )
            }
        };
        let _ = write!(
            self.body,
            "\n{}    #[must_use]\n    pub fn {}(&self{declared}) -> {} {{\n        {body}\n    }}\n",
            indent(&built.doc),
            built.ident,
            built.handle
        );
    }
}

/// `comment`'s lines, indented as a method's.
fn indent(comment: &str) -> String {
    comment.lines().fold(String::new(), |mut text, line| {
        let _ = writeln!(text, "    {line}");
        text
    })
}
