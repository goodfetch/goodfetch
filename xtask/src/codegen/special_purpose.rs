//! The resolved-address classification's table (ADRs 0017 and 0067): every
//! block of IANA's IPv4 and IPv6 special-purpose address registries, which
//! `goodfetch-engine` commits in `iana/` with their date, written as Rust
//! constants beside them in `generated/special_purpose.rs`. A registry that
//! changes without the table being regenerated is drift.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::net::IpAddr;
use std::path::Path;

use anyhow::{Context as _, Result, bail};
use serde::Deserialize;

/// Where the registries are committed, relative to the root.
const FOLDER: &str = "crates/goodfetch-engine/iana";

/// The table, relative to the root.
const TABLE: &str = "crates/goodfetch-engine/generated/special_purpose.rs";

/// Each registry's constant and file stem, IPv4's first.
const REGISTRIES: [(&str, &str); 2] = [
    ("IPV4_REGISTRY", "iana-ipv4-special-registry-1"),
    ("IPV6_REGISTRY", "iana-ipv6-special-registry-1"),
];

/// IANA's columns, in its order.
const HEADER: [&str; 10] = [
    "Address Block",
    "Name",
    "RFC",
    "Allocation Date",
    "Termination Date",
    "Source",
    "Destination",
    "Forwardable",
    "Globally Reachable",
    "Reserved-by-Protocol",
];

/// The "Globally Reachable" column's index.
const GLOBALLY_REACHABLE: usize = 8;

/// The dates a registry's `.source.toml` records.
#[derive(Deserialize)]
struct Source {
    /// When IANA last updated it.
    registry_updated: String,
    /// When it was fetched and committed.
    date: String,
}

/// The table's file from the committed registries; none in a tree that
/// commits no registry, such as a test fixture's.
pub(super) fn generate(root: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    if !root.join(FOLDER).exists() {
        return Ok(BTreeMap::new());
    }
    let mut text = String::from(
        "// Generated by `xtask codegen` from IANA's special-purpose address registries in\n// `iana/`; never edit by hand.\n",
    );
    let mut blocks = String::new();
    for (constant, stem) in REGISTRIES {
        let source_path = root.join(FOLDER).join(format!("{stem}.source.toml"));
        let source: Source = toml::from_str(
            &std::fs::read_to_string(&source_path)
                .with_context(|| format!("reading {}", source_path.display()))?,
        )
        .with_context(|| format!("reading {}", source_path.display()))?;
        let _ = write!(
            text,
            "\n/// `{stem}.csv`: when IANA last updated it, and when it was committed.\npub const {constant}: Registry = Registry {{\n    updated: {:?},\n    committed: {:?},\n}};\n",
            source.registry_updated, source.date,
        );
        let csv_path = root.join(FOLDER).join(format!("{stem}.csv"));
        let csv = std::fs::read_to_string(&csv_path)
            .with_context(|| format!("reading {}", csv_path.display()))?;
        for row in rows(&csv).with_context(|| format!("reading {stem}.csv"))? {
            let _ = writeln!(
                blocks,
                "    // {}/{}\n    Block {{\n        address: {},\n        prefix: {},\n        name: {:?},\n        globally_reachable: {},\n    }},",
                row.address,
                row.prefix,
                address_expression(row.address),
                row.prefix,
                row.name,
                match row.globally_reachable {
                    Some(reachable) => format!("Some({reachable})"),
                    None => "None".to_owned(),
                },
            );
        }
    }
    let _ = write!(
        text,
        "\n/// Every block of both registries, in their files' order; a cell that\n/// lists two blocks gives two.\npub const BLOCKS: &[Block] = &[\n{blocks}];\n"
    );
    Ok(BTreeMap::from([(TABLE.to_owned(), text.into_bytes())]))
}

/// One block of a registry.
struct Row {
    address: IpAddr,
    prefix: u8,
    name: String,
    /// `None` for `N/A`, or a terminated block's empty cell.
    globally_reachable: Option<bool>,
}

/// The blocks of a registry in IANA's CSV form.
fn rows(text: &str) -> Result<Vec<Row>> {
    let mut lines = text.lines();
    if lines.next().map(fields).as_deref() != Some(&HEADER.map(str::to_owned)[..]) {
        bail!("the first line is not IANA's header");
    }
    let mut rows = Vec::new();
    for (index, line) in lines.enumerate() {
        let line_number = index + 2;
        let cells = fields(line);
        if cells.len() != HEADER.len() {
            bail!("line {line_number} lacks the registry's columns");
        }
        let globally_reachable = match without_footnote(&cells[GLOBALLY_REACHABLE]) {
            "True" => Some(true),
            "False" => Some(false),
            "N/A" | "" => None,
            other => bail!("line {line_number}: `{other}` is no reachability"),
        };
        for block in without_footnote(&cells[0]).split(", ") {
            let (address, prefix) = block
                .split_once('/')
                .with_context(|| format!("line {line_number}: `{block}` is no CIDR block"))?;
            let address: IpAddr = address
                .parse()
                .with_context(|| format!("line {line_number}: `{block}` is no CIDR block"))?;
            let prefix: u8 = prefix
                .parse()
                .with_context(|| format!("line {line_number}: `{block}` is no CIDR block"))?;
            if prefix > if address.is_ipv4() { 32 } else { 128 } {
                bail!("line {line_number}: `{block}`'s prefix is too long");
            }
            rows.push(Row {
                address,
                prefix,
                name: cells[1].clone(),
                globally_reachable,
            });
        }
    }
    Ok(rows)
}

/// A CSV line's fields, unquoted.
fn fields(line: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut field = String::new();
    let mut quoted = false;
    let mut characters = line.chars().peekable();
    while let Some(character) = characters.next() {
        match (character, quoted) {
            ('"', true) if characters.peek() == Some(&'"') => {
                characters.next();
                field.push('"');
            }
            ('"', _) => quoted = !quoted,
            (',', false) => fields.push(std::mem::take(&mut field)),
            (character, _) => field.push(character),
        }
    }
    fields.push(field);
    fields
}

/// A cell without IANA's trailing footnote mark, such as ` [1]`.
fn without_footnote(cell: &str) -> &str {
    cell.split(" [").next().unwrap_or(cell)
}

/// `address` as a constant expression, from its bits in groups of four
/// hexadecimal digits: the comment above each block writes it as the
/// registry does.
fn address_expression(address: IpAddr) -> String {
    let (constructor, digits) = match address {
        IpAddr::V4(address) => ("IpAddr::V4(Ipv4Addr", format!("{:08x}", address.to_bits())),
        IpAddr::V6(address) => ("IpAddr::V6(Ipv6Addr", format!("{:032x}", address.to_bits())),
    };
    let groups: Vec<&str> = digits
        .as_bytes()
        .chunks(4)
        .map(|group| std::str::from_utf8(group).unwrap_or_default())
        .collect();
    format!("{constructor}::from_bits(0x{}))", groups.join("_"))
}
