/// Where Foxhound's layer imports Collie's generated layer from.
const CLIENT_PACKAGE: &str = "@goodfetch/collie-client/generated";

/// Where Foxhound's layer imports Collie's types from: their own module,
/// since the generated layer's index gives a handle's name to its class, so
/// a type of that name, such as `Locator`, is reached only here.
const CLIENT_TYPES: &str = "@goodfetch/collie-client/generated/types";

const HEADER: &str = "// Generated by `xtask codegen` from the catalog; never edit by hand.\n";

/// The hand-written module of Collie's client package that declares what
/// sends a call, which its layer's methods take and re-export.
const CALLER_MODULE: &str = "../caller.ts";

pub(super) fn generate(layer: &Layer) -> Result<Generated> {
    // Collie's client package holds the handles (ADR 0117); what Foxhound's
    // operations add to them joins with its own package's ticket.
    let handles = match layer.product {
        Product::Collie => handles::handles(layer)?,
        Product::Foxhound => Vec::new(),
    };
    let (mut input, replaced) = layer
        .generator_input(&format!("{}Types", layer.product.name()), |name| {
            ("tsType", name.to_owned())
        });
    wire::with_date_types(&mut input);
    wire::camel_fields(&mut input)?;
    super::open_values::typescript_input(&mut input);
    super::open_values::unknown_members(&mut input, None)?;
    intersections::fields_beside_members_as_intersections(&mut input);
    // The header comes first, then the imports, then the generator's
    // output, which has no banner of its own.
    let prefix = if replaced.is_empty() {
        format!("{HEADER}\n")
    } else {
        format!("{HEADER}\n{}\n", import_line(&replaced, CLIENT_TYPES))
    };
    let mut files = vec![
        ("index.ts", index(layer, &handles)),
        ("operations.ts", operations(layer)),
        ("events.ts", events(layer)),
        ("errors.ts", errors::errors(layer)?),
        ("plugins.ts", plugins(layer)),
    ];
    files.push(("connection.ts", connection(layer)));
    files.push(("wire.ts", wire::file(layer)?));
    if !layer.shared_types.is_empty() {
        files.push(("shared-types.ts", shared_types(layer)));
    }
    if !handles.is_empty() {
        files.push(("handles.ts", handle_classes(layer, &handles)?));
    }
    // Collie's client package types each scope's `settings` (ADR 0083);
    // Foxhound's types a crawl's and a Label's (ADR 0093).
    files.push((
        "settings.ts",
        match layer.product {
            Product::Collie => settings::settings_module(&layer.settings)?,
            Product::Foxhound => settings::foxhound_settings_module(&layer.settings)?,
        },
    ));
    Ok(Generated {
        files,
        types: TypesFile {
            output: "types.ts",
            input,
            prefix,
            header: String::new(),
        },
    })
}

fn import_line<'a>(names: impl IntoIterator<Item = &'a String>, from: &str) -> String {
    let names: Vec<&str> = names.into_iter().map(String::as_str).collect();
    format!("import type {{ {} }} from \"{from}\";\n", names.join(", "))
}

/// The import lines of the types `names`: the layer's own from `./types.ts`,
/// Collie's from the client package's types module.
fn type_imports(layer: &Layer, names: &BTreeSet<String>) -> String {
    let (collie, own): (BTreeSet<&String>, BTreeSet<&String>) =
        names.iter().partition(|name| layer.is_collie_type(name));
    let mut text = String::new();
    if !collie.is_empty() {
        text.push_str(&import_line(collie, CLIENT_TYPES));
    }
    if !own.is_empty() {
        text.push_str(&import_line(own, "./types.ts"));
    }
    text
}

/// A `TSDoc` comment, indented by `indent`.
fn doc(
    indent: &str,
    description: &str,
    stability: Stability,
    deprecated: Option<&Deprecation>,
) -> String {
    let mut lines: Vec<String> = description
        .replace("*/", "*\\/")
        .lines()
        .map(str::to_owned)
        .collect();
    if stability == Stability::Experimental || deprecated.is_some() {
        lines.push(String::new());
    }
    if stability == Stability::Experimental {
        lines.push("@experimental".to_owned());
    }
    if let Some(deprecated) = deprecated {
        lines.push(format!(
            "@deprecated {}",
            deprecated.message().replace("*/", "*\\/")
        ));
    }
    let mut text = format!("{indent}/**\n");
    for line in lines {
        if line.is_empty() {
            let _ = writeln!(text, "{indent} *");
        } else {
            let _ = writeln!(text, "{indent} * {line}");
        }
    }
    let _ = writeln!(text, "{indent} */");
    text
}

/// Which package holds each main type (ADR 0117), which every entry file a
/// package exports opens with: the layer's `index.ts` is one, its package's
/// `./generated`.
const PACKAGE_MAP: &str = "\
// Where the main types live (ADR 0117): `@goodfetch/collie` holds `Collie`;
// the Collie client package, `@goodfetch/collie-client`, holds `Run`,
// `Session`, `Page` and `Locator`; `@goodfetch/foxhound` holds
// `Foxhound`, `Crawl`, `Label`, `Dataset` and `CrawlContext`.
";

/// The layer's exports, after the map of where the main types live: each
/// type it defines, never the generator's root, which holds no value, and
/// every other module whole. A handle's class takes its name, so a type of
/// that name, the value a handle is built from, stays in `types.ts`.
fn index(layer: &Layer, handles: &[Handle<'_>]) -> String {
    let classes: Vec<String> = handles
        .iter()
        .map(|handle| pascal(handle.namespace))
        .collect();
    let types: Vec<&str> = layer
        .definitions
        .keys()
        .map(String::as_str)
        .filter(|name| !classes.iter().any(|class| class == name))
        .collect();
    let mut text = format!("{HEADER}\n{PACKAGE_MAP}\n");
    if !types.is_empty() {
        let _ = writeln!(
            text,
            "export type {{ {} }} from \"./types.ts\";",
            types.join(", ")
        );
    }
    text.push_str("export * from \"./connection.ts\";\n");
    text.push_str("export * from \"./operations.ts\";\nexport * from \"./events.ts\";\nexport * from \"./errors.ts\";\nexport * from \"./plugins.ts\";\n");
    if !layer.shared_types.is_empty() {
        text.push_str("export type * from \"./shared-types.ts\";\n");
    }
    if !handles.is_empty() {
        text.push_str("export * from \"./handles.ts\";\n");
    }
    match layer.product {
        Product::Collie => text.push_str("export type { PageSettings, RunSettings, SessionSettings, Settings } from \"./settings.ts\";\n"),
        Product::Foxhound => {
            let _ = writeln!(
                text,
                "export type {{ {} }} from \"./settings.ts\";",
                settings::foxhound_types().join(", ")
            );
        }
    }
    text
}

/// Each type both Products share that the layer adds values to (ADR 0095),
/// as a union of its values open to any other string, which the package
/// keeps as received (ADR 0079); Foxhound's adds its values to Collie's.
fn shared_types(layer: &Layer) -> String {
    let mut text = format!("{HEADER}\n");
    let extended: Vec<String> = layer
        .shared_types
        .iter()
        .filter(|shared| shared.extends_collie)
        .map(|shared| {
            let name = pascal(&shared.name);
            format!("{name} as Collie{name}")
        })
        .collect();
    if !extended.is_empty() {
        let _ = writeln!(
            text,
            "import type {{ {} }} from \"{CLIENT_PACKAGE}\";\n",
            extended.join(", ")
        );
    }
    for shared in &layer.shared_types {
        let name = pascal(&shared.name);
        let mut description = if shared.extends_collie {
            format!(
                "A `{}`, a type both Products share (ADR 0095): Collie's values and {}'s own below; a value this package does not know is kept as received (ADR 0079).\n",
                shared.name,
                layer.product.name()
            )
        } else {
            format!(
                "A `{}`, a type both Products share (ADR 0095): {}'s values below; a value this package does not know is kept as received (ADR 0079).\n",
                shared.name,
                layer.product.name()
            )
        };
        for (value, value_description) in &shared.values {
            let _ = write!(description, "\n- `{value}`: {value_description}");
        }
        text.push_str(&doc("", &description, Stability::Stable, None));
        let literals: Vec<String> = shared
            .values
            .iter()
            .map(|(value, _)| format!("{value:?}"))
            .collect();
        if shared.extends_collie {
            let _ = writeln!(
                text,
                "export type {name} = Collie{name} | {};\n",
                literals.join(" | ")
            );
        } else {
            let _ = writeln!(
                text,
                "export type {name} = {} | (string & {{}});\n",
                literals.join(" | ")
            );
        }
    }
    text.truncate(text.trim_end().len());
    text.push('\n');
    text
}

/// What a package's runtime opens a Connection with. Collie's client
/// package holds what both Products' Connections share: the protocol version
/// its `hello` names (ADRs 0024 and 0066), the Product version the package
/// carries (ADRs 0090 and 0095) and the hidden command that serves one
/// Connection. Each Product's layer holds how its own engine is found: its
/// executable and its engine-path variable (ADR 0090). The Connection's
/// messages are among the layer's types.
fn connection(layer: &Layer) -> String {
    let (shared, name, constant, variable) = match layer.product {
        Product::Collie => (
            format!(
                "/** The protocol version `major.minor` this package's `hello` names (ADRs 0024 and 0066). */\nexport const PROTOCOL_VERSION = {:?};\n\n/** The WebSocket subprotocol a Client offers an Exposed Daemon, `goodfetch.v<major>` of the protocol version (ADR 0049). */\nexport const WEBSOCKET_SUBPROTOCOL = {:?};\n\n/** The Product version this package carries, `hello`'s `product_version`, which each Product's package pins exactly (ADRs 0090 and 0095). */\nexport const PRODUCT_VERSION = {:?};\n\n/** The executable's hidden command that serves one Connection over stdio. */\nexport const ATTACHED_ENGINE_COMMAND = {:?};\n\n/** The prefix every deployment variable has, which ADR 0034 reserves. */\nexport const DEPLOYMENT_PREFIX = {DEPLOYMENT_PREFIX:?};\n\n/** The deployment variables, the closed list of `GOODFETCH_` variables `connect()` takes from its environment map (ADR 0083). */\nexport const DEPLOYMENT_VARIABLES = [\n{}\n] as const;\n\n/** The channels an executable can come from, the names `GOODFETCH_CHANNEL` takes (ADR 0090). */\nexport const CHANNELS = [\n{}\n] as const;\n\n/** The project configuration's file `connect()` reads, found in the working directory or the nearest folder above it (ADR 0083). */\nexport const PROJECT_FILE = {PROJECT_CONFIGURATION_FILE:?};\n\n/** The format a project configuration's file is written in, which an unreadable version names (ADR 0030). */\nexport const PROJECT_FORMAT = {:?};\n\n/** The version `major.minor` of that format this package reads (ADR 0030). */\nexport const PROJECT_FORMAT_VERSION = {:?};\n\n",
                layer.protocol_version.to_string(),
                layer.protocol_version.websocket_subprotocol(),
                layer.product_version,
                ATTACHED_ENGINE,
                DEPLOYMENT_VARIABLES
                    .iter()
                    .map(|variable| format!("  {variable:?},"))
                    .collect::<Vec<_>>()
                    .join("\n"),
                CHANNELS
                    .iter()
                    .map(|channel| format!("  {channel:?},"))
                    .collect::<Vec<_>>()
                    .join("\n"),
                USER_CONFIGURATION.name,
                USER_CONFIGURATION.version.to_string(),
            ),
            "Collie",
            "COLLIE",
            COLLIE_ENGINE_PATH_VARIABLE,
        ),
        Product::Foxhound => (
            String::new(),
            "Foxhound",
            "FOXHOUND",
            FOXHOUND_ENGINE_PATH_VARIABLE,
        ),
    };
    format!(
        "{HEADER}\n{shared}/** The variable naming {name}'s executable (ADR 0090). */\nexport const {constant}_ENGINE_PATH_VARIABLE = {variable:?};\n\n/** The name of {name}'s executable (ADR 0090). */\nexport const {constant}_EXECUTABLE = {:?};\n",
        layer.product.executable_name(),
    )
}

fn operations(layer: &Layer) -> String {
    let product = layer.product.name();
    let types: BTreeSet<String> = layer
        .operations
        .iter()
        .flat_map(|operation| [operation.params.0.clone(), operation.result.0.clone()])
        .collect();
    // A read sends nothing, so it has no method of the class (issue 2798).
    let sending: Vec<_> = layer
        .operations
        .iter()
        .filter(|operation| operation.sends())
        .collect();
    // A run layer taken as raw JSON is checked for deprecated keys as a
    // typed member's settings are (ADR 0099).
    let raw_settings_import = if sending
        .iter()
        .any(|operation| layer.takes_raw_settings(operation))
    {
        format!(
            "import {{ {} }} from \"./settings.ts\";\n",
            settings::WARN_DEPRECATED_SETTINGS
        )
    } else {
        String::new()
    };
    let mut text = format!("{HEADER}\n");
    match layer.product {
        Product::Collie => {
            let _ = writeln!(
                text,
                "import type {{ CallOptions, Caller }} from \"{CALLER_MODULE}\";"
            );
            text.push_str(&markers_import(
                sending.iter().copied(),
                MARKERS_MODULE,
                &[ENTRY_MARKERS],
            ));
            text.push_str(&type_imports(layer, &types));
            text.push_str(&raw_settings_import);
            let _ = writeln!(
                text,
                "\nexport type {{ CallOptions, Caller, OperationTypes }} from \"{CALLER_MODULE}\";"
            );
        }
        Product::Foxhound => {
            let _ = writeln!(
                text,
                "import type {{ CallOptions, Caller }} from \"{CLIENT_PACKAGE}\";"
            );
            text.push_str(&markers_import(
                sending.iter().copied(),
                CLIENT_RUNTIME,
                &[ENTRY_MARKERS],
            ));
            text.push_str(&type_imports(layer, &types));
            text.push_str(&raw_settings_import);
        }
    }
    let _ = write!(
        text,
        "\n/** The params and result of each of {product}'s operations. */\nexport interface {product}OperationTypes {{\n"
    );
    for operation in &layer.operations {
        let _ = writeln!(
            text,
            "  {:?}: {{ params: {}; result: {} }};",
            operation.name, operation.params.0, operation.result.0
        );
    }
    let _ = write!(
        text,
        "}}\n\n/** The registry of {product}'s operations, with their markers, which a hand-written member serving one warns of through `warnEntry` (ADR 0099). */\nexport const {}Operations: Readonly<Record<keyof {product}OperationTypes, EntryMarkers>> = {{\n",
        product.to_lowercase()
    );
    for operation in &layer.operations {
        let _ = writeln!(
            text,
            "  {:?}: {},",
            operation.name,
            entry_markers(operation.stability, operation.deprecated.as_ref())
        );
    }
    text.push_str("};\n\n");
    operation_names(&mut text, layer, product);
    operation_classes(&mut text, layer, product);
    let _ = write!(
        text,
        "/** {product}'s operations that send a message, each an async method. */\nexport class {product}Operations {{\n  readonly #caller: Caller<{product}OperationTypes>;\n\n  constructor(caller: Caller<{product}OperationTypes>) {{\n    this.#caller = caller;\n  }}\n"
    );
    for operation in sending {
        text.push('\n');
        text.push_str(&operation_method(layer, operation));
    }
    text.push_str("}\n");
    text
}

/// The map from each operation's catalog name to its TypeScript form.
fn operation_names(text: &mut String, layer: &Layer, product: &str) {
    let _ = write!(
        text,
        "/** The name of each of {product}'s operations in TypeScript form, which the runtime's own errors head a call with (ADR 0079's note of 2026-11-19). */\nexport const {}OperationNames: Readonly<Record<keyof {product}OperationTypes, string>> = {{\n",
        product.to_lowercase()
    );
    for operation in &layer.operations {
        let _ = writeln!(
            text,
            "  {:?}: {:?},",
            operation.name,
            goodfetch_protocol::naming::operation(
                goodfetch_protocol::connection::Form::Typescript,
                &operation.name
            )
        );
    }
    text.push_str("};\n\n");
}

/// The map from each operation's catalog name to its class (ADR 0011),
/// which says whether a call in flight is sent again after a reconnect
/// (ADR 0079).
fn operation_classes(text: &mut String, layer: &Layer, product: &str) {
    let _ = write!(
        text,
        "/** The class of each of {product}'s operations (ADR 0011): after a reconnect, a call in flight is sent again only when it is a read or an idempotent write (ADR 0079). */\nexport const {}OperationClasses: Readonly<Record<keyof {product}OperationTypes, \"read\" | \"idempotent_write\" | \"effect\">> = {{\n",
        product.to_lowercase()
    );
    for operation in &layer.operations {
        let _ = writeln!(
            text,
            "  {:?}: {:?},",
            operation.name,
            operation.class.as_str()
        );
    }
    text.push_str("};\n\n");
}

/// An entry's `EntryMarkers` in a generated registry.
fn entry_markers(stability: Stability, deprecated: Option<&Deprecation>) -> String {
    let deprecated = deprecated.map_or_else(
        || "undefined".to_owned(),
        |deprecated| format!("{:?}", deprecated.message()),
    );
    format!(
        "{{ experimental: {}, deprecated: {deprecated} }}",
        stability == Stability::Experimental
    )
}

fn events(layer: &Layer) -> String {
    let product = layer.product.name();
    let lower = product.to_lowercase();
    let types: BTreeSet<String> = layer
        .events
        .iter()
        .map(|event| event.payload.0.clone())
        .collect();
    let mut text = format!("{HEADER}\n");
    match layer.product {
        Product::Collie => {
            text.push_str(&markers_import([], MARKERS_MODULE, &[ENTRY_MARKERS]));
            text.push_str(&type_imports(layer, &types));
        }
        Product::Foxhound => {
            text.push_str(&markers_import([], CLIENT_RUNTIME, &[ENTRY_MARKERS]));
            text.push_str(&type_imports(layer, &types));
        }
    }
    let _ = write!(
        text,
        "\n/** The payload of each of {product}'s events. */\nexport interface {product}EventPayloads {{\n"
    );
    for event in &layer.events {
        text.push_str(&doc(
            "  ",
            &event.description,
            event.stability,
            event.deprecated.as_ref(),
        ));
        let _ = writeln!(text, "  {:?}: {};", event.name, event.payload.0);
    }
    let _ = write!(
        text,
        "}}\n\n/** The registry of {product}'s events, with their markers. */\nexport const {lower}Events: Readonly<Record<keyof {product}EventPayloads, EntryMarkers>> = {{\n"
    );
    for event in &layer.events {
        let _ = writeln!(
            text,
            "  {:?}: {},",
            event.name,
            entry_markers(event.stability, event.deprecated.as_ref())
        );
    }
    text.push_str("};\n");
    text
}

fn plugins(layer: &Layer) -> String {
    let types: BTreeSet<String> = layer
        .plugin_kinds
        .iter()
        .flat_map(|kind| &kind.methods)
        .flat_map(|method| [method.params.0.clone(), method.result.0.clone()])
        .collect();
    let mut text = format!("{HEADER}\n");
    text.push_str(&type_imports(layer, &types));
    if layer.plugin_kinds.is_empty() {
        text.push_str("export {};\n");
    }
    for kind in &layer.plugin_kinds {
        text.push('\n');
        text.push_str(&doc("", &kind.description, kind.stability, None));
        let _ = writeln!(
            text,
            "export abstract class {}Handler {{",
            pascal(&kind.name)
        );
        for (index, method) in kind.methods.iter().enumerate() {
            if index > 0 {
                text.push('\n');
            }
            text.push_str(&doc("  ", &method.description, Stability::Stable, None));
            let _ = writeln!(
                text,
                "  abstract {}(params: {}): Promise<{}>;",
                camel(&method.name),
                method.params.0,
                method.result.0
            );
        }
        text.push_str("}\n");
    }
    text
}

