//! The TypeScript layer of one SDK package (ADRs 0038 and 0095): types from
//! `json-schema-to-typescript`, and, written here, each operation as an async
//! method, the event registry, one error class per Error code (the seven
//! group classes in Collie's client package, on the base its hand-written
//! `goodfetch-error.ts` declares), the base class of
//! the handlers of each Plugin kind, with the catalog's descriptions as `TSDoc`
//! and its Experimental and deprecated markers. Foxhound's layer imports
//! what Collie's client package defines.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use goodfetch_protocol::catalog::Product;

use super::layer::{Deprecation, Layer, Stability};
use super::naming::{camel, pascal};
use super::{Generated, TypesFile};

/// Where Foxhound's layer imports Collie's generated layer from.
const CLIENT_PACKAGE: &str = "@goodfetch/collie-client/generated";

const HEADER: &str = "// Generated by `xtask codegen` from the catalog; never edit by hand.\n";

/// The hand-written module of Collie's client package that declares what
/// sends a call, which its layer's methods take and re-export.
const CALLER_MODULE: &str = "../caller.ts";

/// The hand-written module of Collie's client package that declares the
/// base of every error class, which its layer's classes extend and
/// re-export.
const GOODFETCH_ERROR_MODULE: &str = "../goodfetch-error.ts";

pub(super) fn generate(layer: &Layer) -> Generated {
    let (input, replaced) = layer
        .generator_input(&format!("{}Types", layer.product.name()), |name| {
            ("tsType", name.to_owned())
        });
    // The header comes first, then the imports, then the generator's
    // output, which has no banner of its own.
    let prefix = if replaced.is_empty() {
        format!("{HEADER}\n")
    } else {
        format!("{HEADER}\n{}\n", import_line(&replaced, CLIENT_PACKAGE))
    };
    let mut files = vec![
        ("index.ts", index(layer)),
        ("operations.ts", operations(layer)),
        ("events.ts", events(layer)),
        ("errors.ts", errors(layer)),
        ("plugins.ts", plugins(layer)),
    ];
    if layer.product == Product::Collie {
        files.push(("connection.ts", connection(layer)));
    }
    if !layer.shared_types.is_empty() {
        files.push(("shared-types.ts", shared_types(layer)));
    }
    Generated {
        files,
        types: TypesFile {
            output: "types.ts",
            input,
            prefix,
            header: String::new(),
        },
    }
}

fn import_line<'a>(names: impl IntoIterator<Item = &'a String>, from: &str) -> String {
    let names: Vec<&str> = names.into_iter().map(String::as_str).collect();
    format!("import type {{ {} }} from \"{from}\";\n", names.join(", "))
}

/// The import lines of the types `names`: the layer's own from `./types.ts`,
/// Collie's from the client package.
fn type_imports(layer: &Layer, names: &BTreeSet<String>) -> String {
    let (collie, own): (BTreeSet<&String>, BTreeSet<&String>) =
        names.iter().partition(|name| layer.is_collie_type(name));
    let mut text = String::new();
    if !collie.is_empty() {
        text.push_str(&import_line(collie, CLIENT_PACKAGE));
    }
    if !own.is_empty() {
        text.push_str(&import_line(own, "./types.ts"));
    }
    text
}

/// A `TSDoc` comment, indented by `indent`.
fn doc(
    indent: &str,
    description: &str,
    stability: Stability,
    deprecated: Option<&Deprecation>,
) -> String {
    let mut lines: Vec<String> = description
        .replace("*/", "*\\/")
        .lines()
        .map(str::to_owned)
        .collect();
    if stability == Stability::Experimental || deprecated.is_some() {
        lines.push(String::new());
    }
    if stability == Stability::Experimental {
        lines.push("@experimental".to_owned());
    }
    if let Some(deprecated) = deprecated {
        lines.push(format!(
            "@deprecated Since {}: {}",
            deprecated.since,
            deprecated.note.replace("*/", "*\\/")
        ));
    }
    let mut text = format!("{indent}/**\n");
    for line in lines {
        if line.is_empty() {
            let _ = writeln!(text, "{indent} *");
        } else {
            let _ = writeln!(text, "{indent} * {line}");
        }
    }
    let _ = writeln!(text, "{indent} */");
    text
}

/// Which package holds each main type (ADR 0117), which every entry file a
/// package exports opens with: the layer's `index.ts` is one, its package's
/// `./generated`.
const PACKAGE_MAP: &str = "\
// Where the main types live (ADR 0117): `@goodfetch/collie` holds `Collie`;
// the Collie client package, `@goodfetch/collie-client`, holds `Run`, and
// will hold `Page`, `Session` and `Locator`; `@goodfetch/foxhound` holds
// `Foxhound`, `Crawl`, `Label`, `Dataset` and `CrawlContext`.
";

/// The layer's exports, after the map of where the main types live: each
/// type it defines, never the generator's root, which holds no value, and
/// every other module whole.
fn index(layer: &Layer) -> String {
    let types: Vec<&str> = layer.definitions.keys().map(String::as_str).collect();
    let mut text = format!("{HEADER}\n{PACKAGE_MAP}\n");
    if !types.is_empty() {
        let _ = writeln!(
            text,
            "export type {{ {} }} from \"./types.ts\";",
            types.join(", ")
        );
    }
    if layer.product == Product::Collie {
        text.push_str("export * from \"./connection.ts\";\n");
    }
    text.push_str("export * from \"./operations.ts\";\nexport * from \"./events.ts\";\nexport * from \"./errors.ts\";\nexport * from \"./plugins.ts\";\n");
    if !layer.shared_types.is_empty() {
        text.push_str("export type * from \"./shared-types.ts\";\n");
    }
    text
}

/// Each type both Products share that the layer adds values to (ADR 0095),
/// as a union of its values open to any other string, which the package
/// keeps as received (ADR 0079); Foxhound's adds its values to Collie's.
fn shared_types(layer: &Layer) -> String {
    let mut text = format!("{HEADER}\n");
    let extended: Vec<String> = layer
        .shared_types
        .iter()
        .filter(|shared| shared.extends_collie)
        .map(|shared| {
            let name = pascal(&shared.name);
            format!("{name} as Collie{name}")
        })
        .collect();
    if !extended.is_empty() {
        let _ = writeln!(
            text,
            "import type {{ {} }} from \"{CLIENT_PACKAGE}\";\n",
            extended.join(", ")
        );
    }
    for shared in &layer.shared_types {
        let name = pascal(&shared.name);
        let mut description = if shared.extends_collie {
            format!(
                "A `{}`, a type both Products share (ADR 0095): Collie's values and {}'s own below; a value this package does not know is kept as received (ADR 0079).\n",
                shared.name,
                layer.product.name()
            )
        } else {
            format!(
                "A `{}`, a type both Products share (ADR 0095): {}'s values below; a value this package does not know is kept as received (ADR 0079).\n",
                shared.name,
                layer.product.name()
            )
        };
        for (value, value_description) in &shared.values {
            let _ = write!(description, "\n- `{value}`: {value_description}");
        }
        text.push_str(&doc("", &description, Stability::Stable, None));
        let literals: Vec<String> = shared
            .values
            .iter()
            .map(|(value, _)| format!("{value:?}"))
            .collect();
        if shared.extends_collie {
            let _ = writeln!(
                text,
                "export type {name} = Collie{name} | {};\n",
                literals.join(" | ")
            );
        } else {
            let _ = writeln!(
                text,
                "export type {name} = {} | (string & {{}});\n",
                literals.join(" | ")
            );
        }
    }
    text.truncate(text.trim_end().len());
    text.push('\n');
    text
}

/// What the client package's runtime opens a Connection with: the protocol
/// version its `hello` names (ADRs 0024 and 0066) and the Product version
/// the package carries (ADRs 0090 and 0095). The Connection's messages are
/// among the layer's types.
fn connection(layer: &Layer) -> String {
    format!(
        "{HEADER}\n/** The protocol version `major.minor` this package's `hello` names (ADRs 0024 and 0066). */\nexport const PROTOCOL_VERSION = {:?};\n\n/** The Product version this package carries, `hello`'s `product_version`, which each Product's package pins exactly (ADRs 0090 and 0095). */\nexport const PRODUCT_VERSION = {:?};\n",
        layer.protocol_version, layer.product_version
    )
}

fn operations(layer: &Layer) -> String {
    let product = layer.product.name();
    let types: BTreeSet<String> = layer
        .operations
        .iter()
        .flat_map(|operation| [operation.params.0.clone(), operation.result.0.clone()])
        .collect();
    let mut text = format!("{HEADER}\n");
    match layer.product {
        Product::Collie => {
            let _ = writeln!(
                text,
                "import type {{ CallOptions, Caller }} from \"{CALLER_MODULE}\";"
            );
            text.push_str(&type_imports(layer, &types));
            let _ = writeln!(
                text,
                "\nexport type {{ CallOptions, Caller, OperationTypes }} from \"{CALLER_MODULE}\";"
            );
        }
        Product::Foxhound => {
            let _ = writeln!(
                text,
                "import type {{ CallOptions, Caller }} from \"{CLIENT_PACKAGE}\";"
            );
            text.push_str(&type_imports(layer, &types));
        }
    }
    let _ = write!(
        text,
        "\n/** The params and result of each of {product}'s operations. */\nexport interface {product}OperationTypes {{\n"
    );
    for operation in &layer.operations {
        let _ = writeln!(
            text,
            "  {:?}: {{ params: {}; result: {} }};",
            operation.name, operation.params.0, operation.result.0
        );
    }
    let _ = write!(
        text,
        "}}\n\n/** {product}'s operations, each an async method. */\nexport class {product}Operations {{\n  readonly #caller: Caller<{product}OperationTypes>;\n\n  constructor(caller: Caller<{product}OperationTypes>) {{\n    this.#caller = caller;\n  }}\n"
    );
    for operation in &layer.operations {
        text.push('\n');
        text.push_str(&doc(
            "  ",
            &operation.description,
            operation.stability,
            operation.deprecated.as_ref(),
        ));
        let method = camel(&operation.name);
        let (params, result) = (&operation.params.0, &operation.result.0);
        if operation.cancellable {
            let _ = write!(
                text,
                "  {method}(params: {params}, options: CallOptions = {{}}): Promise<{result}> {{\n    return this.#caller.call({:?}, params, options);\n  }}\n",
                operation.name
            );
        } else {
            let _ = write!(
                text,
                "  {method}(params: {params}): Promise<{result}> {{\n    return this.#caller.call({:?}, params, {{}});\n  }}\n",
                operation.name
            );
        }
    }
    text.push_str("}\n");
    text
}

fn events(layer: &Layer) -> String {
    let product = layer.product.name();
    let lower = product.to_lowercase();
    let types: BTreeSet<String> = layer
        .events
        .iter()
        .map(|event| event.payload.0.clone())
        .collect();
    let mut text = format!("{HEADER}\n");
    match layer.product {
        Product::Collie => {
            text.push_str(&type_imports(layer, &types));
            text.push_str(
                "\n/** An event's markers. */\nexport interface EventMarkers {\n  readonly experimental: boolean;\n  readonly deprecated: string | undefined;\n}\n",
            );
        }
        Product::Foxhound => {
            let _ = writeln!(
                text,
                "import type {{ EventMarkers }} from \"{CLIENT_PACKAGE}\";"
            );
            text.push_str(&type_imports(layer, &types));
        }
    }
    let _ = write!(
        text,
        "\n/** The payload of each of {product}'s events. */\nexport interface {product}EventPayloads {{\n"
    );
    for event in &layer.events {
        text.push_str(&doc(
            "  ",
            &event.description,
            event.stability,
            event.deprecated.as_ref(),
        ));
        let _ = writeln!(text, "  {:?}: {};", event.name, event.payload.0);
    }
    let _ = write!(
        text,
        "}}\n\n/** The registry of {product}'s events, with their markers. */\nexport const {lower}Events: Readonly<Record<keyof {product}EventPayloads, EventMarkers>> = {{\n"
    );
    for event in &layer.events {
        let deprecated = event.deprecated.as_ref().map_or_else(
            || "undefined".to_owned(),
            |deprecated| {
                format!(
                    "{:?}",
                    format!("Since {}: {}", deprecated.since, deprecated.note)
                )
            },
        );
        let _ = writeln!(
            text,
            "  {:?}: {{ experimental: {}, deprecated: {deprecated} }},",
            event.name,
            event.stability == Stability::Experimental,
        );
    }
    text.push_str("};\n");
    text
}

fn group_class(group: &str) -> String {
    format!("{}Error", pascal(group))
}

fn errors(layer: &Layer) -> String {
    let product = layer.product.name();
    let lower = product.to_lowercase();
    let mut text = format!("{HEADER}\n");
    match layer.product {
        Product::Collie => {
            let _ = write!(
                text,
                "import {{ GoodfetchError, type ErrorClass, type ErrorFields }} from \"{GOODFETCH_ERROR_MODULE}\";\n\nexport {{ GoodfetchError, type ErrorClass, type ErrorFields }};\n\n/** The seven groups of Error codes, named for their remedy (ADR 0079). */\nexport type ErrorGroup = {};\n",
                layer
                    .error_groups
                    .iter()
                    .map(|group| format!("{:?}", group.name))
                    .collect::<Vec<_>>()
                    .join(" | ")
            );
            for group in &layer.error_groups {
                text.push('\n');
                text.push_str(&doc("", &group.description, Stability::Stable, None));
                let _ = writeln!(
                    text,
                    "export class {} extends GoodfetchError {{}}",
                    group_class(&group.name)
                );
            }
            text.push_str(
                "\n/** The group of each JSON-RPC error code the engine answers with, its wire class (ADR 0038). */\nexport const errorGroupOfWireClass: Readonly<Record<number, ErrorGroup>> = {\n",
            );
            for group in &layer.error_groups {
                let _ = writeln!(text, "  [{}]: {:?},", group.json_rpc_class, group.name);
            }
            text.push_str(
                "};\n\n/** The class of each group, which raises a code the SDK does not know, keeping the code (ADR 0079). */\nexport const errorGroupClasses: Readonly<Record<ErrorGroup, typeof GoodfetchError>> = {\n",
            );
            for group in &layer.error_groups {
                let _ = writeln!(text, "  {}: {},", group.name, group_class(&group.name));
            }
            text.push_str("};\n");
            text.push_str(&exit_codes(layer));
        }
        Product::Foxhound => {
            let imported: BTreeSet<String> = layer
                .error_codes
                .iter()
                .map(|code| group_class(&code.group))
                .collect();
            let names: Vec<String> = imported.into_iter().collect();
            let _ = writeln!(
                text,
                "import {{ {} }} from \"{CLIENT_PACKAGE}\";\nimport type {{ ErrorClass, ErrorFields }} from \"{CLIENT_PACKAGE}\";",
                names.join(", ")
            );
        }
    }
    let mut registry = Vec::new();
    for code in &layer.error_codes {
        // A code named like its group is raised as its group's class,
        // which every code the registry lacks falls back to.
        if code.name == code.group {
            continue;
        }
        let group = group_class(&code.group);
        let class = format!("{}Error", pascal(&code.name));
        text.push('\n');
        text.push_str(&doc("", &code.description, Stability::Stable, None));
        let _ = write!(
            text,
            "export class {class} extends {group} {{\n  constructor(message: string, fields: ErrorFields = {{}}) {{\n    super(message, {{ ...fields, code: {:?}, group: {:?}, retryable: {} }});\n  }}\n}}\n",
            code.name, code.group, code.retryable
        );
        registry.push((code.name.clone(), class));
    }
    let _ = write!(
        text,
        "\n/** The error class of each of {product}'s Error codes. */\nexport const {lower}ErrorClasses: Readonly<Record<string, ErrorClass>> = {{\n"
    );
    for (code, class) in registry {
        let _ = writeln!(text, "  {code}: {class},");
    }
    text.push_str("};\n");
    text
}

/// ADR 0069's exit codes of a failed command, which the `goodfetch-collie`
/// bin exits with when it cannot run the executable: each group's row, and
/// each Error code's own row, which wins. Nothing when the projection lists
/// no exit-code table (the codegen fixture's).
fn exit_codes(layer: &Layer) -> String {
    let groups: Option<Vec<(&str, u8)>> = layer
        .error_groups
        .iter()
        .map(|group| group.exit_code.map(|code| (group.name.as_str(), code)))
        .collect();
    let Some(groups) = groups else {
        return String::new();
    };
    let mut text = String::from(
        "\n/** The CLI's exit code of a failure with each group's Error codes, unless the code has a row of its own (ADR 0069). */\nexport const errorGroupExitCodes: Readonly<Record<ErrorGroup, number>> = {\n",
    );
    for (group, code) in groups {
        let _ = writeln!(text, "  {group}: {code},");
    }
    text.push_str(
        "};\n\n/** The Error codes with an exit code of their own, which wins over their group's (ADR 0069). */\nexport const errorCodeExitCodes: Readonly<Record<string, number>> = {\n",
    );
    for code in &layer.error_codes {
        if let Some(exit) = code.exit_code {
            let _ = writeln!(text, "  {}: {exit},", code.name);
        }
    }
    text.push_str("};\n");
    text
}

fn plugins(layer: &Layer) -> String {
    let types: BTreeSet<String> = layer
        .plugin_kinds
        .iter()
        .flat_map(|kind| &kind.methods)
        .flat_map(|method| [method.params.0.clone(), method.result.0.clone()])
        .collect();
    let mut text = format!("{HEADER}\n");
    text.push_str(&type_imports(layer, &types));
    if layer.plugin_kinds.is_empty() {
        text.push_str("export {};\n");
    }
    for kind in &layer.plugin_kinds {
        text.push('\n');
        text.push_str(&doc("", &kind.description, kind.stability, None));
        let _ = writeln!(
            text,
            "export abstract class {}Handler {{",
            pascal(&kind.name)
        );
        for (index, method) in kind.methods.iter().enumerate() {
            if index > 0 {
                text.push('\n');
            }
            text.push_str(&doc("  ", &method.description, Stability::Stable, None));
            let _ = writeln!(
                text,
                "  abstract {}(params: {}): Promise<{}>;",
                camel(&method.name),
                method.params.0,
                method.result.0
            );
        }
        text.push_str("}\n");
    }
    text
}
