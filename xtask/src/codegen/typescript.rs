//! The TypeScript layer of one SDK package (ADRs 0038 and 0095): types from
//! `json-schema-to-typescript`, and, written here, each operation as an async
//! method, the event registry, one error class per Error code (the seven
//! group classes in Collie's client package, on the base its hand-written
//! `goodfetch-error.ts` declares), the base class of
//! the handlers of each Plugin kind, with the catalog's descriptions as `TSDoc`
//! and its Experimental and deprecated markers. Foxhound's layer imports
//! what Collie's client package defines.

