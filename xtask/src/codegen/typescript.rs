/// A positional parameter's name in a declaration.
fn positional_name(name: &str) -> String {
    let spelled = camel(name);
    if RESERVED_WORDS.contains(&spelled.as_str()) || spelled == "options" {
        format!("{spelled}_")
    } else {
        spelled
    }
}

/// A method's parameter list and the object it makes of it, which starts
/// with the handle's ID as `id`: positional parameters first, then the
/// options object, which holds the named ones and, for a call that can be
/// cancelled, `signal`. Each type is the params type's own,
/// `types.<Params>["<name>"]`, but the one the fields that type a result
/// are declared by, `typed`, which is the member's type parameter. A call's
/// own `timeout` goes through `timeoutOf`, which refuses before sending a
/// value no deadline can be, naming its setting, `timeout_setting`
/// (ADR 0080). A scope's own `settings` take that scope's settings type,
/// `settings_type`, and go through `settingsOnWire`, which sends them by
/// their wire spelling (ADR 0083).
fn signature(
    parameters: &Parameters,
    type_name: &str,
    cancellable: bool,
    id: &str,
    typed: Option<&str>,
    timeout_setting: Option<&str>,
    settings_type: Option<&str>,
) -> (String, String) {
    let mut declared = Vec::new();
    let mut entries = vec![format!("{id}: this.#host.id")];
    for name in &parameters.positional {
        let local = positional_name(name);
        if typed == Some(name.as_str()) {
            declared.push(format!("{local}: {FIELDS}"));
        } else {
            declared.push(format!("{local}: types.{type_name}[{name:?}]"));
        }
        entries.push(if local == *name {
            local
        } else {
            format!("{name}: {local}")
        });
    }
    let mut options = Vec::new();
    for name in &parameters.named {
        options.push(format!(
            "readonly {}: types.{type_name}[{name:?}]",
            camel(name)
        ));
        entries.push(format!("{name}: options.{}", camel(name)));
    }
    for name in &parameters.optional {
        let given = format!("options.{}", camel(name));
        if let Some(settings) = settings_type.filter(|_| name == SETTINGS) {
            options.push(format!("readonly {}?: {settings} | undefined", camel(name)));
            entries.push(format!("{name}: {}({given})", settings::SETTINGS_ON_WIRE));
        } else {
            options.push(format!(
                "readonly {}?: types.{type_name}[{name:?}] | undefined",
                camel(name)
            ));
            entries.push(match timeout_setting.filter(|_| name == TIMEOUT) {
                Some(setting) => format!("{name}: {TIMEOUT_OF}({given}, {setting:?})"),
                None => format!("{name}: {given}"),
            });
        }
    }
    if cancellable {
        options.push("readonly signal?: AbortSignal | undefined".to_owned());
    }
    if !options.is_empty() {
        let default = if parameters.named.is_empty() {
            " = {}"
        } else {
            ""
        };
        declared.push(format!("options: {{ {} }}{default}", options.join("; ")));
    }
    let object = format!("{{ {} }}", entries.join(", "));
    // An optional parameter left out is left out of the object, never sent
    // as `undefined`.
    let object = if parameters.optional.is_empty() {
        object
    } else {
        format!("defined({object})")
    };
    (declared.join(", "), object)
}

/// The type `member` answers: the operation's result type, or the type of
/// its one property, which an optional one gives with `null` for absent.
fn answered(member: &Member<'_>, result: &str) -> String {
    match &member.unwrapped {
        None => format!("types.{result}"),
        Some(unwrapped) if unwrapped.required => {
            format!("types.{result}[{:?}]", unwrapped.property)
        }
        Some(unwrapped) => {
            format!(
                "NonNullable<types.{result}[{:?}]> | null",
                unwrapped.property
            )
        }
    }
}

/// What `member` returns of `call`: its result, or its result's one
/// property, `null` when an optional one is absent.
fn answer(member: &Member<'_>, call: &str) -> String {
    match &member.unwrapped {
        None => call.to_owned(),
        Some(unwrapped) if unwrapped.required => {
            format!("(await {call}).{}", unwrapped.property)
        }
        Some(unwrapped) => format!("(await {call}).{} ?? null", unwrapped.property),
    }
}

/// One member, a method of the class that holds `host`.
fn member(member: &Member<'_>, id: &HandleId) -> Result<String> {
    let operation = member.operation;
    let (params, result) = (&operation.params.0, &operation.result.0);
    let typed = member.typed_by.as_ref();
    let (declared, sent) = signature(
        &member.parameters,
        params,
        operation.cancellable,
        &id.param,
        typed.map(|typed| typed.param.as_str()),
        member.timeout_setting.as_deref(),
        settings::scope_settings(member)?,
    );
    let call_options = if operation.cancellable {
        "{ signal: options.signal }"
    } else {
        "{}"
    };
    let call = format!(
        "this.#host.call({:?}, {sent}, {call_options})",
        operation.name
    );
    let mut text = doc(
        "  ",
        &operation.description,
        operation.stability,
        operation.deprecated.as_ref(),
    );
    let name = camel(member.name);
    let warn = warnings(operation);
    match &member.form {
        Form::RoundTrip | Form::Query | Form::Waiter => match typed {
            None => {
                let _ = write!(
                    text,
                    "  async {name}({declared}): Promise<{}> {{\n{warn}    return {};\n  }}\n",
                    answered(member, result),
                    answer(member, &call)
                );
            }
            // Its result is typed by the fields the caller passes, which
            // the member takes as a type parameter (ADR 0147).
            Some(typed) => {
                let typed_result =
                    format!("TypedBy<types.{result}, {:?}, {FIELDS}>", typed.property);
                let _ = write!(
                    text,
                    "  async {name}<const {FIELDS} extends types.{params}[{:?}]>({declared}): Promise<{typed_result}> {{\n{warn}    return typedBy<types.{result}, {:?}, {FIELDS}>(await {call});\n  }}\n",
                    typed.param, typed.property
                );
            }
        },
        Form::Opens(opened) => {
            let class = pascal(opened);
            let _ = write!(
                text,
                "  async {name}({declared}): Promise<{class}> {{\n{warn}    const opened = await {call};\n    return new {class}(this.#host.child(opened.{opened}_id));\n  }}\n"
            );
        }
        Form::Closes => {
            let _ = write!(
                text,
                "  async {name}({declared}): Promise<void> {{\n{warn}    await this.#host.close({:?}, {sent});\n  }}\n",
                operation.name
            );
        }
    }
    Ok(text)
}

/// The handles module's header and imports: the field values' types only
/// when a member's result is typed by the fields it declares (ADR 0147),
/// and the `events` registry only when a handle listens.
fn handles_imports(handles: &[Handle<'_>], operation_types: &str, events: &str) -> Result<String> {
    let typed = handles.iter().any(|handle| {
        handle
            .members
            .iter()
            .chain(handle.sub_objects.iter().flat_map(|held| &held.members))
            .any(|member| member.typed_by.is_some())
    });
    let field_values = if typed {
        format!("import {{ typedBy, type TypedBy }} from \"{FIELD_VALUES_MODULE}\";\n")
    } else {
        String::new()
    };
    let timed = handles.iter().any(|handle| {
        handle
            .members
            .iter()
            .chain(handle.sub_objects.iter().flat_map(|held| &held.members))
            .any(|member| member.timeout_setting.is_some())
    });
    let timeout_of = if timed {
        format!(", {TIMEOUT_OF}")
    } else {
        String::new()
    };
    let listens = handles
        .iter()
        .any(|handle| handle.listener.is_some() || handle.published_listener.is_some());
    let markers = markers_import(
        handles.iter().flat_map(|handle| {
            handle
                .members
                .iter()
                .chain(handle.sub_objects.iter().flat_map(|held| &held.members))
                .map(|member| member.operation)
                .chain(
                    handle
                        .listener
                        .iter()
                        .chain(&handle.published_listener)
                        .map(|listener| listener.operation),
                )
        }),
        MARKERS_MODULE,
        if listens { &[WARN_ENTRY] } else { &[] },
    );
    let (listener_types, registry) = if listens {
        (
            ", type Listener, type Subscription",
            format!("import {{ {events} }} from \"./events.ts\";\n"),
        )
    } else {
        ("", String::new())
    };
    let settings = settings::handles_import(handles)?;
    Ok(format!(
        "{HEADER}\n{field_values}import {{ defined{timeout_of}, type HandleHost{listener_types} }} from \"{HANDLE_MODULE}\";\n{markers}import {{ Handle }} from \"{RAW_CALL_MODULE}\";\n{registry}import type {{ {operation_types} }} from \"./operations.ts\";\n{settings}import type * as types from \"./types.ts\";\n"
    ))
}

/// The classes of `handle`'s sub-objects (ADR 0099), each holding the
/// host of the `class` it belongs to.
fn sub_object_classes(class: &str, host: &str, handle: &Handle<'_>) -> Result<String> {
    let mut text = String::new();
    for sub_object in &handle.sub_objects {
        let sub_class = format!("{class}{}", pascal(sub_object.name));
        let _ = write!(
            text,
            "\n/** The `{}` of a `{class}` (ADR 0099). */\nexport class {sub_class} {{\n  readonly #host: {host};\n\n  /** @internal A `{class}` holds its own; a program never constructs one. */\n  constructor(host: {host}) {{\n    this.#host = host;\n  }}\n",
            camel(sub_object.name)
        );
        for held in &sub_object.members {
            text.push('\n');
            text.push_str(&member(held, &handle.id)?);
        }
        text.push_str("}\n");
    }
    Ok(text)
}

/// The handles of Collie's client package (ADR 0099): one class a
/// namespace, with its members in the form their kind gives them, the
/// values it builds without a call and its sub-objects.
fn handle_classes(layer: &Layer, handles: &[Handle<'_>]) -> Result<String> {
    let operation_types = format!("{}OperationTypes", layer.product.name());
    let events = format!("{}Events", layer.product.name().to_lowercase());
    let mut text = handles_imports(handles, &operation_types, &events)?;
    for handle in handles {
        let class = pascal(handle.namespace);
        let host = format!(
            "HandleHost<types.{}, {operation_types}>",
            handle.id.type_name
        );
        text.push_str(&sub_object_classes(&class, &host, handle)?);
        let implements = if handle.closes() {
            " implements AsyncDisposable"
        } else {
            ""
        };
        let (listened, on) = listeners::emit(&class, handle, &host, &events);
        text.push_str(&listened);
        let id_type = format!("types.{}", handle.id.type_name);
        let _ = write!(
            text,
            "\nlet idIn{class}: (handle: {class}) => {id_type};\n\n/** @internal The ID `handle`'s calls carry, for a Product's package whose own calls name it (ADR 0093); never for programs. */\nexport function idOf{class}(handle: {class}): {id_type} {{\n  return idIn{class}(handle);\n}}\n"
        );
        let _ = write!(
            text,
            "\n/** A `{}` a program holds: the members the catalog gives it (ADR 0099). */\nexport class {class} extends Handle{implements} {{\n  static {{\n    idIn{class} = (handle) => handle.#host.id;\n  }}\n\n  readonly #host: {host};\n",
            handle.namespace
        );
        for sub_object in &handle.sub_objects {
            let _ = writeln!(
                text,
                "  /** Its `{name}`. */\n  readonly {name}: {class}{};",
                pascal(sub_object.name),
                name = camel(sub_object.name)
            );
        }
        let _ = write!(
            text,
            "\n  /** @internal The engine's answer, or the handle that builds it, makes one; a program never constructs one. */\n  constructor(host: {host}) {{\n    super(host, {:?}, {:?});\n    this.#host = host;\n",
            handle.namespace, handle.id.param
        );
        for sub_object in &handle.sub_objects {
            let _ = writeln!(
                text,
                "    this.{} = new {class}{}(host);",
                camel(sub_object.name),
                pascal(sub_object.name)
            );
        }
        text.push_str("  }\n");
        for held in &handle.members {
            text.push('\n');
            text.push_str(&member(held, &handle.id)?);
        }
        text.push_str(&on);
        for builder in &handle.builders {
            let built = pascal(&builder.builds);
            let (declared, value) = signature(
                &builder.parameters,
                &builder.type_name,
                false,
                &handle.id.param,
                None,
                None,
                None,
            );
            text.push('\n');
            text.push_str(&doc(
                "  ",
                &format!(
                    "{}\n\nBuilt without a call (ADR 0099).",
                    builder.description
                ),
                Stability::Stable,
                None,
            ));
            let _ = write!(
                text,
                "  {}({declared}): {built} {{\n    return new {built}(this.#host.child<types.{}>({value}));\n  }}\n",
                camel(&builder.builds),
                builder.type_name
            );
        }
        if handle.closes() {
            text.push_str(
                "\n  async [Symbol.asyncDispose](): Promise<void> {\n    await this.close();\n  }\n",
            );
        }
        text.push_str("}\n");
    }
    Ok(text)
}
