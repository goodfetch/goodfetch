/// The documented signatures that come before `member`'s implementation:
/// its doc alone, or each overload: the current one, then one per
/// deprecated form, which a call resolves to and a linter reports, then one
/// that takes every form; the implementation's signature is then hidden
/// (ADR 0099).
fn overloads(
    member: &Member<'_>,
    name: &str,
    generics: &str,
    returns: &str,
    signature_of: impl Fn(Overload<'_>) -> (String, String),
) -> String {
    let operation = member.operation;
    let forms = &member.deprecated_forms;
    if forms.is_empty() {
        return doc(
            "  ",
            &operation.description,
            operation.stability,
            operation.deprecated.as_ref(),
        );
    }
    let (current, _) = signature_of(Overload::Current(forms));
    let mut text = doc("  ", &operation.description, operation.stability, None);
    let _ = writeln!(text, "  {name}{generics}({current}): {returns};");
    for form in forms {
        let (declared, _) = signature_of(Overload::Deprecated(form));
        let passed = match &form.value {
            Some(value) => format!("`{}: {value:?}`", camel(&form.param)),
            None => format!("`{}`", camel(&form.param)),
        };
        text.push_str(&doc(
            "  ",
            &format!(
                "{}\n\nPassing {passed} is deprecated.",
                operation.description
            ),
            operation.stability,
            Some(&form.deprecation),
        ));
        let _ = writeln!(text, "  {name}{generics}({declared}): {returns};");
    }
    // Last, one that takes every form, as the implementation does, so a
    // call whose value only its type gives, a union or an optional one,
    // still resolves: an overload free of no form, which has no default.
    let (every, _) = signature_of(Overload::Current(&[]));
    text.push_str(&doc(
        "  ",
        &operation.description,
        operation.stability,
        None,
    ));
    let _ = writeln!(text, "  {name}{generics}({every}): {returns};");
    text
}

/// One member, a method of the class that holds `host`.
fn member(member: &Member<'_>, id: &HandleId) -> Result<String> {
    let operation = member.operation;
    let (params, result) = (&operation.params.0, &operation.result.0);
    let typed = member.typed_by.as_ref();
    let settings_type = settings::scope_settings(member)?;
    let signature_of = |overload: Overload<'_>| {
        signature(
            &member.parameters,
            params,
            operation.cancellable,
            &id.param,
            typed.map(|typed| typed.param.as_str()),
            member.timeout_setting.as_deref(),
            settings_type,
            overload,
        )
    };
    let (declared, sent) = signature_of(Overload::Every);
    // A call's own timeout also bounds its wait in the Client's queue under
    // the engine's cap on calls in flight (ADR 0038; issue 2529).
    let mut options = Vec::new();
    if operation.cancellable {
        options.push("signal: options.signal".to_owned());
    }
    if let Some(setting) = &member.timeout_setting {
        options.push(format!(
            "deadline: {{ key: {setting:?}, value: options.{TIMEOUT} }}"
        ));
    }
    let call_options = if options.is_empty() {
        "{}".to_owned()
    } else {
        format!("{{ {} }}", options.join(", "))
    };
    let call = format!(
        "this.#host.call({:?}, {sent}, {call_options})",
        operation.name
    );
    let name = camel(member.name);
    let warn = warnings(operation);
    // The type parameters, the result type and the body of the method.
    let (generics, returns, body) = match &member.form {
        Form::RoundTrip | Form::Query | Form::Waiter => match typed {
            None => (
                String::new(),
                format!("Promise<{}>", answered(member, result)),
                answer(member, &call),
            ),
            // Its result is typed by the fields the caller passes, which
            // the member takes as a type parameter (ADR 0147).
            Some(typed) => (
                format!(
                    "<const {FIELDS} extends types.{params}[{:?}]>",
                    camel(&typed.param)
                ),
                format!(
                    "Promise<TypedBy<types.{result}, {:?}, {FIELDS}>>",
                    camel(&typed.property)
                ),
                format!(
                    "    return typedBy<types.{result}, {:?}, {FIELDS}>(await {call});\n",
                    camel(&typed.property)
                ),
            ),
        },
        Form::Opens(opened) => {
            let class = pascal(opened);
            let id = camel(&format!("{opened}_id"));
            (
                String::new(),
                format!("Promise<{class}>"),
                format!(
                    "    const opened = await {call};\n{}",
                    holders::opened(member.holding.as_ref(), &class, &id)
                ),
            )
        }
        Form::Closes => (
            String::new(),
            "Promise<void>".to_owned(),
            format!(
                "    await this.#host.close({:?}, {sent});\n",
                operation.name
            ),
        ),
    };
    let mut text = overloads(member, &name, &generics, &returns, signature_of);
    let _ = write!(
        text,
        "  async {name}{generics}({declared}): {returns} {{\n{warn}{body}  }}\n"
    );
    Ok(text)
}

/// The handles module's header and imports: the field values' types only
/// when a member's result is typed by the fields it declares (ADR 0147),
/// and the `events` registry only when a handle listens, with the types of
/// a value an event opens only when one does (ADR 0081).
fn handles_imports(handles: &[Handle<'_>], operation_types: &str, events: &str) -> Result<String> {
    let typed = handles.iter().any(|handle| {
        handle
            .members
            .iter()
            .chain(handle.sub_objects.iter().flat_map(|held| &held.members))
            .any(|member| member.typed_by.is_some())
    });
    let field_values = if typed {
        format!("import {{ typedBy, type TypedBy }} from \"{FIELD_VALUES_MODULE}\";\n")
    } else {
        String::new()
    };
    let timed = handles.iter().any(|handle| {
        handle
            .members
            .iter()
            .chain(handle.sub_objects.iter().flat_map(|held| &held.members))
            .any(|member| member.timeout_setting.is_some())
    });
    let timeout_of = if timed {
        format!(", {TIMEOUT_OF}")
    } else {
        String::new()
    };
    let listens = handles
        .iter()
        .any(|handle| handle.listener.is_some() || handle.published_listener.is_some());
    let markers = markers_import(
        handles.iter().flat_map(|handle| {
            handle
                .members
                .iter()
                .chain(handle.sub_objects.iter().flat_map(|held| &held.members))
                .map(|member| member.operation)
                .chain(handle.reads().iter().map(|read| read.operation))
                .chain(
                    handle
                        .listener
                        .iter()
                        .chain(&handle.published_listener)
                        .map(|listener| listener.operation),
                )
        }),
        MARKERS_MODULE,
        if listens { &[WARN_ENTRY] } else { &[] },
    );
    let opens = handles
        .iter()
        .flat_map(|handle| &handle.listener)
        .any(handles::Listener::opens);
    let (listener_types, registry) = if listens {
        (
            if opens {
                ", type Listener, type OpenedEvents, type Opens, type Subscription"
            } else {
                ", type Listener, type Subscription"
            },
            format!("import {{ {events} }} from \"./events.ts\";\n"),
        )
    } else {
        ("", String::new())
    };
    let settings = settings::handles_import(handles)?;
    let response = response_import(handles);
    Ok(format!(
        "{HEADER}\n{field_values}import {{ defined{timeout_of}, type HandleHost{listener_types} }} from \"{HANDLE_MODULE}\";\n{markers}import {{ Handle }} from \"{RAW_CALL_MODULE}\";\n{response}{registry}import type {{ {operation_types} }} from \"./operations.ts\";\n{settings}import type * as types from \"./types.ts\";\n"
    ))
}

/// `read`, a sync method that answers its value of the answer that opened
/// its handle, `opened`, which the handle holds: it sends nothing (issue
/// 2798).
fn read_member(read: &handles::Read<'_>, opened: &str) -> String {
    let operation = read.operation;
    let property = camel(&read.property);
    format!(
        "{}  {}(): types.{opened}[{property:?}] {{\n{}    return this.#opened.{property};\n  }}\n",
        doc(
            "  ",
            &operation.description,
            operation.stability,
            operation.deprecated.as_ref(),
        ),
        camel(read.name),
        warnings(operation)
    )
}

/// The classes of `handle`'s sub-objects (ADR 0099), each holding the
/// host of the `class` it belongs to.
fn sub_object_classes(class: &str, host: &str, handle: &Handle<'_>) -> Result<String> {
    let mut text = String::new();
    for sub_object in &handle.sub_objects {
        let sub_class = format!("{class}{}", pascal(sub_object.name));
        let _ = write!(
            text,
            "\n/** The `{}` of a `{class}` (ADR 0099). */\nexport class {sub_class} {{\n  readonly #host: {host};\n\n  /** @internal A `{class}` holds its own; a program never constructs one. */\n  constructor(host: {host}) {{\n    this.#host = host;\n  }}\n",
            camel(sub_object.name)
        );
        for held in &sub_object.members {
            text.push('\n');
            text.push_str(&member(held, &handle.id)?);
        }
        text.push_str("}\n");
    }
    Ok(text)
}

/// The methods of `handle` that build a value without a call (ADR 0099).
fn builder_members(handle: &Handle<'_>) -> String {
    let mut text = String::new();
    for builder in &handle.builders {
        let built = pascal(&builder.builds);
        let (declared, value) = signature(
            &builder.parameters,
            &builder.type_name,
            false,
            &handle.id.param,
            None,
            None,
            None,
            Overload::Every,
        );
        text.push('\n');
        text.push_str(&doc(
            "  ",
            &format!(
                "{}\n\nBuilt without a call (ADR 0099).",
                builder.description
            ),
            Stability::Stable,
            None,
        ));
        let _ = write!(
            text,
            "  {}({declared}): {built} {{\n    return new {built}(this.#host.child<types.{}>({value}));\n  }}\n",
            camel(&builder.builds),
            builder.type_name
        );
    }
    text
}

/// The handles of Collie's client package (ADR 0099): one class a
/// namespace, with its members in the form their kind gives them, the
/// values it builds without a call and its sub-objects.
fn handle_classes(layer: &Layer, handles: &[Handle<'_>]) -> Result<String> {
    let operation_types = format!("{}OperationTypes", layer.product.name());
    let events = format!("{}Events", layer.product.name().to_lowercase());
    let mut text = handles_imports(handles, &operation_types, &events)?;
    for handle in handles {
        let class = pascal(handle.namespace);
        let host = format!(
            "HandleHost<types.{}, {operation_types}>",
            handle.id.type_name
        );
        text.push_str(&sub_object_classes(&class, &host, handle)?);
        let implements = if handle.closes() {
            " implements AsyncDisposable"
        } else {
            ""
        };
        let (listened, on) = listeners::emit(&class, handle, &host, &events);
        text.push_str(&listened);
        let id_type = format!("types.{}", handle.id.type_name);
        let _ = write!(
            text,
            "\nlet idIn{class}: (handle: {class}) => {id_type};\n\n/** @internal The ID `handle`'s calls carry, for a Product's package whose own calls name it (ADR 0093); never for programs. */\nexport function idOf{class}(handle: {class}): {id_type} {{\n  return idIn{class}(handle);\n}}\n"
        );
        let _ = write!(
            text,
            "\n/** A `{}` a program holds: the members the catalog gives it (ADR 0099). */\nexport class {class} extends Handle{implements} {{\n  static {{\n    idIn{class} = (handle) => handle.#host.id;\n  }}\n\n  readonly #host: {host};\n",
            handle.namespace
        );
        let opened = handle.reads.as_ref().map(|reads| &reads.opened);
        if let Some(opened) = opened {
            let _ = writeln!(text, "  readonly #opened: types.{opened};");
        }
        text.push_str(&holders::fields(handle, &operation_types));
        for sub_object in &handle.sub_objects {
            let _ = writeln!(
                text,
                "  /** Its `{name}`. */\n  readonly {name}: {class}{};",
                pascal(sub_object.name),
                name = camel(sub_object.name)
            );
        }
        let opened_param = format!(
            "{}{}",
            opened.map_or(String::new(), |opened| format!(", opened: types.{opened}")),
            holders::parameter(handle)
        );
        let _ = write!(
            text,
            "\n  /** @internal The engine's answer, or the handle that builds it, makes one; a program never constructs one. */\n  constructor(host: {host}{opened_param}) {{\n    super(host, {:?}, {:?}, {{ type: {:?} }});\n    this.#host = host;\n",
            handle.namespace, handle.id.param, handle.id.type_name
        );
        if opened.is_some() {
            text.push_str("    this.#opened = opened;\n");
        }
        text.push_str(&holders::assignment(handle));
        for sub_object in &handle.sub_objects {
            let _ = writeln!(
                text,
                "    this.{} = new {class}{}(host);",
                camel(sub_object.name),
                pascal(sub_object.name)
            );
        }
        text.push_str("  }\n");
        text.push_str(&holders::members(handle, &operation_types));
        for held in &handle.members {
            text.push('\n');
            text.push_str(&member(held, &handle.id)?);
        }
        if let Some(reads) = &handle.reads {
            for read in &reads.members {
                text.push('\n');
                text.push_str(&read_member(read, &reads.opened));
            }
        }
        text.push_str(&on);
        text.push_str(&builder_members(handle));
        if handle.closes() {
            text.push_str(
                "\n  async [Symbol.asyncDispose](): Promise<void> {\n    await this.close();\n  }\n",
            );
        }
        text.push_str("}\n");
    }
    Ok(text)
}
