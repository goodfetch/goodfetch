//! `xtask chromium expectations check` (ADR 0074; TESTING.md, The Goodfetch
//! Chromium): the expectations under `chromium/expectations/`, the gtest
//! filter files and the two wptrunner metadata trees, checked on their own
//! and against a run's JUnit results of both builds and the recheck of the
//! Control build. One fixture per refused case, each one edit away from a
//! clean fixture that passes. The local tooling declares no Feature.

use std::fmt::Write as _;

use rstest::rstest;

use crate::workspace::{Outcome, Workspace, finding};

const FILTER: &str = "chromium/expectations/gtest/unit_tests-linux.filter";
const GENERATED: &str = "chromium/expectations/gtest/generated/unit_tests-linux.filter";
const CONTROL_A: &str = "chromium/expectations/wpt/control/css/a.html.ini";
const GOODFETCH_A: &str = "chromium/expectations/wpt/goodfetch/css/a.html.ini";
const GOODFETCH_B: &str = "chromium/expectations/wpt/goodfetch/canvas/b.html.ini";

const UPSTREAM_LINE: &str = "# upstream link=https://issues.chromium.org/issues/1\n";
const FLAKY_LINE: &str = "# upstream-flaky issue=#10 upstream=https://issues.chromium.org/issues/2 run=https://github.com/goodfetch/goodfetch/actions/runs/3 date=2026-11-01\n";
const GENERATED_HEADER: &str =
    "# Generated by: xtask chromium expectations regenerate unit_tests\n# Tracking issue: #11\n";

/// One test case of a JUnit file: its class name, its name and whether it
/// passed.
type Case<'a> = (&'a str, &'a str, bool);

fn junit(cases: &[Case<'_>]) -> String {
    let mut xml = String::from("<testsuites><testsuite name=\"run\">");
    for (class, name, passed) in cases {
        let name = name.replace('>', "&gt;");
        let ending = if *passed {
            ""
        } else {
            "<failure message=\"failed\"/>"
        };
        write!(
            xml,
            "<testcase classname=\"{class}\" name=\"{name}\">{ending}</testcase>"
        )
        .unwrap();
    }
    xml.push_str("</testsuite></testsuites>\n");
    xml
}

/// Expectations with one entry of each category in each format, and results
/// of both builds and a recheck that agree with them.
fn clean() -> Workspace {
    let workspace = Workspace::from_fixture("empty");
    workspace.write(
        FILTER,
        format!(
            "{UPSTREAM_LINE}-UpstreamTest.Fails\n\n{FLAKY_LINE}-FlakyTest.Varies\n\n# intended patch=0001-canvas.patch surface=canvas.toDataURL\n-CanvasTest.Exact\n"
        )
        .as_bytes(),
    );
    workspace.write(
        GENERATED,
        format!("{GENERATED_HEADER}# upstream-flaky rate=1.5%\n-LuciTest.Flakes\n").as_bytes(),
    );
    let upstream = "[a.html]\n  category: upstream link=https://issues.chromium.org/issues/4\n  expected: FAIL\n";
    workspace.write(CONTROL_A, upstream.as_bytes());
    workspace.write(GOODFETCH_A, upstream.as_bytes());
    workspace.write(
        GOODFETCH_B,
        b"[b.html]\n  [exact pixels]\n    category: intended patch=0001-canvas.patch surface=canvas.toDataURL\n    expected: FAIL\n",
    );
    workspace.write(
        "results/control/gtest-linux.xml",
        junit(&[("unit_tests", "UpstreamTest.Fails", false)]).as_bytes(),
    );
    workspace.write(
        "results/control/wpt.xml",
        junit(&[("wpt", "/css/a.html", false)]).as_bytes(),
    );
    workspace.write(
        "results/goodfetch/wpt.xml",
        junit(&[
            ("wpt", "/css/a.html", false),
            ("wpt", "/canvas/b.html > exact pixels", false),
        ])
        .as_bytes(),
    );
    let mut recheck = vec![("unit_tests", "FlakyTest.Varies", true); 19];
    recheck.push(("unit_tests", "FlakyTest.Varies", false));
    workspace.write(
        "results/recheck/gtest-linux.xml",
        junit(&recheck).as_bytes(),
    );
    workspace
}

fn check(workspace: &Workspace, today: &str) -> Outcome {
    workspace.xtask(&[
        "chromium",
        "expectations",
        "check",
        "--platform",
        "linux",
        "--control",
        "results/control",
        "--goodfetch",
        "results/goodfetch",
        "--recheck",
        "results/recheck",
        "--today",
        today,
    ])
}

#[test]
fn clean_expectations_pass() {
    let workspace = clean();

    let outcome = check(&workspace, "2026-11-24");

    assert_eq!(outcome.code, 0, "{}{}", outcome.stdout, outcome.stderr);
    assert_eq!(outcome.findings(), []);
}

#[test]
fn the_static_checks_pass_without_results() {
    let workspace = clean();

    let outcome = workspace.xtask(&["chromium", "expectations", "check", "--today", "2026-11-24"]);

    assert_eq!(outcome.code, 0, "{}{}", outcome.stdout, outcome.stderr);
}

fn no_category(workspace: &Workspace) {
    workspace.edit(FILTER, UPSTREAM_LINE, "");
}

fn no_evidence(workspace: &Workspace) {
    workspace.edit(FILTER, UPSTREAM_LINE, "# upstream\n");
}

fn flaky_without_its_issue(workspace: &Workspace) {
    workspace.edit(FILTER, "issue=#10 ", "");
}

fn wpt_entry_without_category(workspace: &Workspace) {
    workspace.edit(
        CONTROL_A,
        "  category: upstream link=https://issues.chromium.org/issues/4\n",
        "",
    );
}

fn generated_without_its_command(workspace: &Workspace) {
    workspace.edit(
        GENERATED,
        "# Generated by: xtask chromium expectations regenerate unit_tests\n",
        "",
    );
}

fn trees_differ(workspace: &Workspace) {
    workspace.edit(CONTROL_A, "expected: FAIL", "expected: TIMEOUT");
}

fn widened(workspace: &Workspace) {
    workspace.edit(GOODFETCH_B, "expected: FAIL", "expected: [PASS, FAIL]");
}

fn upstream_passes_on_the_control_build(workspace: &Workspace) {
    workspace.write(
        "results/control/wpt.xml",
        junit(&[("wpt", "/css/a.html", true)]).as_bytes(),
    );
}

fn expected_failure_passes(workspace: &Workspace) {
    workspace.write(
        "results/goodfetch/wpt.xml",
        junit(&[
            ("wpt", "/css/a.html", false),
            ("wpt", "/canvas/b.html > exact pixels", true),
        ])
        .as_bytes(),
    );
}

fn exclusion_passes_on_the_control_build(workspace: &Workspace) {
    workspace.write(
        "results/control/gtest-linux.xml",
        junit(&[("unit_tests", "UpstreamTest.Fails", true)]).as_bytes(),
    );
}

fn stale(workspace: &Workspace) {
    workspace.write(
        "results/recheck/gtest-linux.xml",
        junit(&[("unit_tests", "FlakyTest.Varies", true); 20]).as_bytes(),
    );
}

#[rstest]
#[case::an_entry_with_no_category(no_category, "uncategorized", "unit_tests UpstreamTest.Fails")]
#[case::an_entry_with_no_evidence(no_evidence, "no-evidence", "unit_tests UpstreamTest.Fails")]
#[case::a_flaky_entry_without_its_issue(
    flaky_without_its_issue,
    "no-evidence",
    "unit_tests FlakyTest.Varies"
)]
#[case::a_metadata_entry_with_no_category(
    wpt_entry_without_category,
    "uncategorized",
    "wpt /css/a.html"
)]
#[case::a_generated_file_without_its_command(
    generated_without_its_command,
    "no-evidence",
    "gtest/generated/unit_tests-linux.filter"
)]
#[case::metadata_trees_differing_outside_intended(trees_differ, "trees-differ", "wpt /css/a.html")]
#[case::a_widened_goodfetch_expectation(widened, "widened", "wpt /canvas/b.html > exact pixels")]
#[case::an_upstream_entry_passing_on_the_control_build(
    upstream_passes_on_the_control_build,
    "upstream-passed",
    "wpt /css/a.html"
)]
#[case::an_expected_failure_that_passed(
    expected_failure_passes,
    "expected-failure-passed",
    "wpt /canvas/b.html > exact pixels"
)]
#[case::a_gtest_exclusion_passing_on_the_control_build(
    exclusion_passes_on_the_control_build,
    "exclusion-passed",
    "unit_tests UpstreamTest.Fails"
)]
#[case::a_stale_entry(stale, "stale", "unit_tests FlakyTest.Varies")]
fn a_refused_case_fails(#[case] edit: fn(&Workspace), #[case] kind: &str, #[case] subject: &str) {
    let workspace = clean();
    edit(&workspace);

    let outcome = check(&workspace, "2026-11-24");

    assert_eq!(outcome.code, 1, "{}{}", outcome.stdout, outcome.stderr);
    assert_eq!(outcome.findings(), [finding(kind, subject)]);
}

#[test]
fn an_entry_not_renewed_within_8_weeks_expires() {
    let workspace = clean();

    let renewed = check(&workspace, "2026-12-27");
    let expired = check(&workspace, "2026-12-28");

    assert_eq!(renewed.code, 0, "{}{}", renewed.stdout, renewed.stderr);
    assert_eq!(expired.code, 1, "{}{}", expired.stdout, expired.stderr);
    assert_eq!(
        expired.findings(),
        [finding("expired", "unit_tests FlakyTest.Varies")]
    );
}
